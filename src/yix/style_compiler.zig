//! `.yss` -> Zig: style recipe file.
//! Top-level `recipe` / `style` / `mixin` are style DSL; rest copied as-is to Zig (import,
//! data-dependent styleBy functions).
//! DSL maps one-to-one to `ui.cva` / `ui.sva` / `ui.css`, zero runtime: output is plain object
//! literals.
//!
//! ```
//! const ui = @import("../../ui.zig");
//!
//! /// Card root
//! recipe Card {
//!   base { direction: column; background: bg-primary; corner-radius: 6; transition: background
//!   120ms ease-out; }
//!   variant variant = default {
//!     default  { border: 1 border; }
//!     elevated { shadow: md; }
//!   }
//!   flag selected { border: 2 accent; }
//!   flag hoverable;
//!   when hoverable & !selected & variant in (default, elevated) { :hover { background: bg-hover; }
//!   }
//! }
//!
//! recipe Tag slots(root, label) {
//!   base { root { gap: 4; } label { font-size: sm; } }
//!   variant color = neutral { neutral { label { color: fg-primary; } } accent { tone(accent); } }
//! }
//!
//! mixin tone(fg) { root { background: mix(bg-primary, fg, 0.25); } label { color: fg; } }
//!
//! style title { color: fg-primary; font-size: 14; font-weight: 600; }
//! ```
//!
//! Values: number = pixels / raw; name = token or enum (`bg-primary` -> `.bg_primary`, lookup by
//! field token category);
//! `transparent`; `#rrggbb`; `mix(a, b, w)`; `{zig expression}` embedded as-is. `grow` for
//! width/height = fill remaining space.
//! Shorthands: `padding` / `margin` take 1 / 2 (vert horiz) / 4 (top right bottom left) values;
//! `border: width [color]`; `transition: ...` entire segment is transition description.
//! Condition blocks: `:hover` `:active` `:focus` `:selected` `:expanded` `:invalid` `:disabled`.
