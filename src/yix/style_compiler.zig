const Compound = struct { when: std.ArrayList([2][]const u8) = .empty, body: *Body };

const Compiler = struct {
    a: Allocator,
    src: []const u8,
    capture_ir: bool = false,
    preview_path: ?[]const u8 = null,
    ir_declarations: std.ArrayList(ir.Declaration) = .empty,
    dependency_hash: u64 = 0,
    pos: usize = 0,
    diag: ?Diagnostic = null,
    mixins: std.StringHashMapUnmanaged(Mixin) = .empty,
    /// Parameter substitution during mixin expansion (name -> value at call site)
    subst: ?*const std.StringHashMapUnmanaged(Val) = null,
    /// Current recipe's slots (sva); null = single-block recipe (cva/css)
    slots: ?[][]const u8 = null,
    /// Mixin expansion depth (prevent self-recursion)
    depth: usize = 0,
    /// Parameters of parameterized style being compiled; null = not in parameterized style (`$name`
    /// is error)
    params: ?[]Param = null,
    /// Top-level `when` blocks of parameterized style collected here; null = cannot write `when` in
    /// current block
    param_whens: ?*std.ArrayList(ParamWhen) = null,
    /// A `{zig}` value in the block being compiled reads the theme (`t`): a plain style holding
    /// one resolves per theme, like a parameterized style.
    uses_theme: bool = false,
    /// First interactive state / transition in the block (source offset): a theme-reading plain
    /// style resolves like a parameterized one, so it cannot carry either.
    first_state_at: ?usize = null,
    first_transition_at: ?usize = null,

    /// Block hierarchy: top level of slot recipe (base/options/when blocks) holds only slot blocks;
    /// slot blocks and single-block recipe hold properties
    const Level = enum { flat, slots };

    fn topLevel(c: *const Compiler) Level {
        return if (c.slots != null) .slots else .flat;
    }

    fn fail(c: *Compiler, at: usize, comptime fmt: []const u8, args: anytype) Error {
        c.diag = .{ .offset = at, .message = try std.fmt.allocPrint(c.a, fmt, args) };
        return error.Yss;
    }

    // -- Top level: copy Zig as-is, dispatch DSL declarations to parser --

    fn run(c: *Compiler) Error![]const u8 {
        const found = try findDecls(c.a, c.src);
        if (found.err) |e| return c.fail(e.offset, "{s}", .{e.message});
        const decls = found.decls;
        if (c.capture_ir) {
            var h = std.hash.Wyhash.init(0);
            var cursor: usize = 0;
            for (decls) |d| {
                hashDependency(&h, c.src[cursor..d.start]);
                if (d.kind == .mixin) h.update(c.src[d.start..d.end]);
                cursor = d.end;
            }
            hashDependency(&h, c.src[cursor..]);
            c.dependency_hash = h.final();
        }
        // Register mixins first (declaration order doesn't matter), then generate recipes
        for (decls) |d| if (d.kind == .mixin) {
            c.pos = d.keyword + "mixin".len;
            try c.mixinDecl();
        };
        var out: std.ArrayList(u8) = .empty;
        var at: usize = 0;
        for (decls) |d| {
            // Mixin doesn't generate code: preceding doc comment must also be removed (orphaned
            // `///` is not valid Zig)
            const keep_end = if (d.kind == .mixin) docCommentStart(c.src, d.start) else d.start;
            try c.exact(&out, at, c.src[at..keep_end]);
            c.pos = d.keyword + @tagName(d.kind).len;
            if (d.kind != .mixin) try @import("list_writer.zig").init(c.a, &out).print("{c}{d}{c}", .{ compiler.mark_point, d.start, compiler.mark_text });
            switch (d.kind) {
                .recipe => try c.recipeDecl(&out),
                .style => try c.styleDecl(&out),
                .mixin => {},
            }
            if (d.kind != .mixin) try out.append(c.a, compiler.mark_close);
            at = d.end;
        }
        try c.exact(&out, at, c.src[at..]);
        return out.items;
    }

    // Declaration insertion adds separator whitespace to copied-Zig spans.
    // Hash nonempty dependency spans with boundaries, so that whitespace alone
    // cannot turn an otherwise supported unused style addition into L3.
    fn hashDependency(h: *std.hash.Wyhash, source: []const u8) void {
        const content = std.mem.trim(u8, source, " \t\r\n");
        if (content.len == 0) return;
        h.update(std.mem.asBytes(&content.len));
        h.update(content);
    }

    /// Copied source text: wrap with byte-by-byte mapping marks; copied Zig: replace source
    /// filename @import (`"x.yss"`/`"x.yix"`) with twin name, rest maps byte-by-byte
    fn exact(c: *Compiler, out: *std.ArrayList(u8), at: usize, piece: []const u8) Error!void {
        try compiler.markZig(c.a, out, piece, at);
    }

    fn matchBrace(c: *Compiler, from: usize, depth0: usize) ?usize {
        return matchBraceIn(c.src, from, depth0);
    }

    // -- Lexical --

    fn skipSpace(c: *Compiler) void {
        c.pos = lex(c.src, c.pos).tok.start;
    }

    fn next(c: *Compiler) Error!Tok {
        const r = lex(c.src, c.pos);
        if (r.tok.tag == .other) return c.fail(r.tok.start, "unexpected character `{c}`", .{c.src[r.tok.start]});
        c.pos = r.next;
        return r.tok;
    }

    fn peek(c: *Compiler) Error!Tok {
        const save = c.pos;
        defer c.pos = save;
        return c.next();
    }

    fn expect(c: *Compiler, tag: Tag, what: []const u8) Error!Tok {
        const t = try c.next();
        if (t.tag != tag) return c.fail(t.start, "expected {s}", .{what});
        return t;
    }

    fn text(c: *const Compiler, t: Tok) []const u8 {
        return c.src[t.start..t.end];
    }

    /// Name used in generated code as field name (slots, dimensions, options, recipe/mixin
    /// parameters): Zig identifier, not keyword, no hyphens
    fn fieldName(c: *Compiler, t: Tok, what: []const u8) Error![]const u8 {
        const n = c.text(t);
        if (std.mem.indexOfScalar(u8, n, '-') != null) return c.fail(t.start, "{s} `{s}` must be a Zig identifier (no `-`; use `_` or camelCase)", .{ what, n });
        if (std.zig.Token.getKeyword(n) != null) return c.fail(t.start, "{s} `{s}` is a Zig keyword", .{ what, n });
        // Naming convention: recipes PascalCase (generate types); styles, slots, dimensions
        // snake_case (`close_icon`, no Style suffix).
        // Only governs YSS declaration names; copied Zig follows Zig conventions
        if (eq(what, "recipe")) {
            if (!std.ascii.isUpper(n[0])) return c.fail(t.start, "recipe `{s}` is a type: name it in PascalCase (e.g. `{c}{s}`)", .{ n, std.ascii.toUpper(n[0]), n[1..] });
        } else if (eq(what, "style") or eq(what, "slot") or eq(what, "variant") or eq(what, "flag")) {
            for (n) |ch| if (std.ascii.isUpper(ch)) return c.fail(t.start, "{s} `{s}` should be snake_case (e.g. `{s}`)", .{ what, n, try snakeOf(c.a, n) });
            if (eq(what, "style") and std.mem.endsWith(u8, n, "_style")) return c.fail(t.start, "style `{s}`: drop the `_style` suffix (it is a style already)", .{n});
        }
        // Dimension name same as recipe keyword (`variant variant`) reads like syntax error; name
        // by intent
        if (eq(what, "variant") or eq(what, "flag")) for ([_][]const u8{ "base", "variant", "flag", "when", "in" }) |kw| {
            if (eq(n, kw)) return c.fail(t.start, "{s} `{s}` has the same name as a YSS keyword; name it after what it means (e.g. `variant kind`)", .{ what, n });
        };
        return n;
    }

    fn snake(c: *Compiler, name: []const u8) Error![]const u8 {
        const out = try c.a.dupe(u8, name);
        for (out) |*ch| if (ch.* == '-') {
            ch.* = '_';
        };
        return out;
    }

    // -- Declaration --

    fn mixinDecl(c: *Compiler) Error!void {
        const name_t = try c.expect(.ident, "a mixin name");
        _ = try c.expect(.lparen, "`(` and the mixin parameters");
        var params: std.ArrayList([]const u8) = .empty;
        if ((try c.peek()).tag == .rparen) {
            _ = try c.next();
        } else while (true) {
            const p = try c.expect(.ident, "a parameter name");
            for (params.items) |x| if (eq(x, c.text(p))) return c.fail(p.start, "parameter `{s}` is listed twice", .{x});
            try params.append(c.a, c.text(p));
            const sep = try c.next();
            if (sep.tag == .rparen) break;
            if (sep.tag != .comma) return c.fail(sep.start, "expected `,` or `)`", .{});
        }
        const open = try c.expect(.lbrace, "`{` and the mixin body");
        const name = c.text(name_t);
        if (c.mixins.contains(name)) return c.fail(name_t.start, "mixin `{s}` is declared twice", .{name});
        try c.mixins.put(c.a, name, .{ .params = params.items, .body_start = open.end, .at = name_t.start });
    }

    fn previewFactory(c: *Compiler, out: *std.ArrayList(u8), name: []const u8, comptime factory: []const u8) Error!void {
        const path = c.preview_path.?;
        try @import("list_writer.zig").init(c.a, &out).print("ui.{s}(\"{f}\", \"{f}\", @embedFile(\"{f}\"), ", .{
            factory, std.zig.fmtString(path), std.zig.fmtString(name), std.zig.fmtString(std.fs.path.basename(path)),
        });
    }

    fn styleDecl(c: *Compiler, out: *std.ArrayList(u8)) Error!void {
        const name_t = try c.expect(.ident, "a style name");
        _ = try c.fieldName(name_t, "style");
        c.slots = null;
        if ((try c.peek()).tag == .lparen) return c.paramStyleDecl(out, name_t);
        _ = try c.expect(.lbrace, "`{`");
        const body = try c.a.create(Body);
        body.* = .{};
        c.uses_theme = false;
        c.first_state_at = null;
        c.first_transition_at = null;
        defer {
            c.uses_theme = false;
            c.first_state_at = null;
            c.first_transition_at = null;
        }
        try c.bodyUntilClose(body, .flat);
        if (c.capture_ir) try c.ir_declarations.append(c.a, .{
            .name = c.text(name_t),
            .kind = if (c.uses_theme) .param_style else .style,
            .base = try body.lower(c.a),
            .offset = name_t.start,
            .signature = if (c.uses_theme) c.src[name_t.start..c.pos] else "",
        });
        if (c.uses_theme) {
            if (c.first_state_at) |at| return c.fail(at, "a style whose `{{…}}` reads the theme (`t`) resolves like a parameterized style and cannot hold interactive states (`:hover` …); put the states in a recipe or another plain style on the same node", .{});
            if (c.first_transition_at) |at| return c.fail(at, "a style whose `{{…}}` reads the theme (`t`) cannot declare transitions; declare them in a recipe or another plain style on the same node", .{});
            // `{… t …}`: the theme is only known at resolve time, so the style is a resolver
            // without parameters (same runtime as `style name($p) { … }`), placed as `.of(.{})`.
            const w = @import("list_writer.zig").init(c.a, &out);
            try w.print("pub const {s} = ui.paramStyle(struct {{ pub const declared = &[_][]const u8{{", .{c.text(name_t)});
            for (body.keys.items) |k| try w.print(" \"{s}\",", .{k});
            try out.appendSlice(c.a, " }; pub fn resolve(args: @This(), t: *const ui.theme.Values) ui.BoxStyle { _ = args; return ui.boxFrom(");
            try body.emit(c.a, out);
            try out.appendSlice(c.a, ", t); } }).of(.{});");
            return;
        }
        try out.appendSlice(c.a, "pub const ");
        try out.appendSlice(c.a, c.text(name_t));
        try out.appendSlice(c.a, " = ");
        if (c.preview_path != null) try c.previewFactory(out, c.text(name_t), "previewCss") else try out.appendSlice(c.a, "ui.css(");
        try body.emit(c.a, out);
        try out.appendSlice(c.a, ");");
    }

    /// Parameterized style: `style name($p: T = default, ...) { properties...; when condition {
    /// properties... } }`, generates `ui.paramStyle(struct { param fields...; resolve })`.
    /// Top-level properties are base; `when` blocks stack on base in write order (later overrides
    /// earlier, consistent with recipe base -> variants order).
    fn paramStyleDecl(c: *Compiler, out: *std.ArrayList(u8), name_t: Tok) Error!void {
        _ = try c.next();
        var params: std.ArrayList(Param) = .empty;
        if ((try c.peek()).tag == .rparen) return c.fail(name_t.start, "a parameterized style needs at least one parameter (drop the `()` for a plain style)", .{});
        while (true) {
            const pt = try c.next();
            // Trailing comma (multi-line params follow Zig convention)
            if (pt.tag == .rparen and params.items.len != 0) break;
            if (pt.tag != .param) return c.fail(pt.start, "expected a parameter like `$width: f32`", .{});
            const pname = c.src[pt.start + 1 .. pt.end];
            if (std.zig.Token.getKeyword(pname) != null) return c.fail(pt.start, "parameter `${s}` is a Zig keyword", .{pname});
            for ([_][]const u8{ "resolve", "declared" }) |r| if (eq(pname, r)) return c.fail(pt.start, "parameter name `${s}` is reserved", .{pname});
            for (params.items) |x| if (eq(x.name, pname)) return c.fail(pt.start, "parameter `${s}` is listed twice", .{pname});
            _ = try c.expect(.colon, "`:` and the parameter type (`$width: f32`)");
            const ty = try c.zigUntil("a parameter type", "=,)");
            var param: Param = .{ .name = pname, .at = pt.start, .ty = ty.text, .ty_at = ty.at, .default = null, .default_at = 0 };
            var stop = c.src[c.pos];
            c.pos += 1;
            if (stop == '=') {
                const d = try c.zigUntil("a default value", ",)");
                param.default = d.text;
                param.default_at = d.at;
                stop = c.src[c.pos];
                c.pos += 1;
            }
            try params.append(c.a, param);
            if (stop == ')') break;
        }
        _ = try c.expect(.lbrace, "`{` and the style body");
        var whens: std.ArrayList(ParamWhen) = .empty;
        c.params = params.items;
        c.param_whens = &whens;
        defer {
            c.params = null;
            c.param_whens = null;
        }
        const base = try c.a.create(Body);
        base.* = .{};
        try c.bodyUntilClose(base, .flat);
        if (c.capture_ir) try c.ir_declarations.append(c.a, .{
            .name = c.text(name_t),
            .kind = .param_style,
            .base = try base.lower(c.a),
            .signature = c.src[name_t.start..c.pos],
            .offset = name_t.start,
        });
        for (params.items) |p| if (!p.used) return c.fail(p.at, "parameter `${s}` is never used", .{p.name});

        const w = @import("list_writer.zig").init(c.a, &out);
        try w.print("pub const {s} = ui.paramStyle(struct {{", .{c.text(name_t)});
        for (params.items) |p| {
            try w.print(" {s}: {s}", .{ p.name, try c.rawMapped(p.ty, p.ty_at) });
            if (p.default) |d| try w.print(" = {s}", .{try c.rawMapped(d, p.default_at)});
            try out.append(c.a, ',');
        }
        // All properties written (regardless of condition): runtime reserves StyleExt based on this
        try out.appendSlice(c.a, " pub const declared = &[_][]const u8{");
        var seen: std.StringHashMapUnmanaged(void) = .empty;
        for (base.keys.items) |k| if (!(try seen.getOrPut(c.a, k)).found_existing) try w.print(" \"{s}\",", .{k});
        for (whens.items) |wh| for (wh.body.keys.items) |k| if (!(try seen.getOrPut(c.a, k)).found_existing) try w.print(" \"{s}\",", .{k});
        try out.appendSlice(c.a, " }; pub fn resolve(args: @This(), t: *const ui.theme.Values) ui.BoxStyle {");
        if (whens.items.len == 0) {
            try out.appendSlice(c.a, " return ui.boxFrom(");
            try base.emit(c.a, out);
            try out.appendSlice(c.a, ", t);");
        } else {
            if (base.keys.items.len == 0) {
                try out.appendSlice(c.a, " var out: ui.BoxStyle = .{};");
            } else {
                try out.appendSlice(c.a, " var out = ui.boxFrom(");
                try base.emit(c.a, out);
                try out.appendSlice(c.a, ", t);");
            }
            for (whens.items) |wh| {
                try w.print(" if ({s}) out = out.merge(ui.boxFrom(", .{wh.cond});
                try wh.body.emit(c.a, out);
                try out.appendSlice(c.a, ", t));");
            }
            try out.appendSlice(c.a, " return out;");
        }
        try out.appendSlice(c.a, " } });");
    }

    /// Zig source segment in parameter list (type/default): read until one of `stops` at depth 0
    /// (don't consume it), recognize brackets, strings, comments
    fn zigUntil(c: *Compiler, what: []const u8, stops: []const u8) Error!struct { text: []const u8, at: usize } {
        const start = c.pos;
        var depth: usize = 0;
        var i = c.pos;
        while (i < c.src.len) : (i += 1) {
            const ch = c.src[i];
            if (skipZigLiteral(c.src, i)) |end| {
                i = end;
                continue;
            }
            switch (ch) {
                '(', '[', '{' => {
                    depth += 1;
                    continue;
                },
                ')', ']', '}' => if (depth > 0) {
                    depth -= 1;
                    continue;
                },
                else => {},
            }
            if (depth == 0 and std.mem.indexOfScalar(u8, stops, ch) != null) break;
            if (depth == 0 and (ch == '}' or ch == ']')) return c.fail(i, "unexpected `{c}` in {s}", .{ ch, what });
        } else return c.fail(start, "unterminated parameter list (missing `)`)", .{});
        const piece = c.src[start..i];
        const text_ = std.mem.trim(u8, piece, " \t\r\n");
        if (text_.len == 0) return c.fail(i, "expected {s}", .{what});
        c.pos = i;
        return .{ .text = text_, .at = start + (piece.len - std.mem.trimStart(u8, piece, " \t\r\n").len) };
    }

    /// Raw Zig text with byte-by-byte mapping back to source
    fn rawMapped(c: *Compiler, text_: []const u8, at: usize) Error![]const u8 {
        return std.fmt.allocPrint(c.a, "{c}{d}{c}{s}{c}", .{ compiler.mark_open, at, compiler.mark_text, text_, compiler.mark_close });
    }

    /// `$name`: parameter in current parameterized style (register as used)
    fn useParam(c: *Compiler, name: []const u8, at: usize) Error!*Param {
        const params = c.params orelse return c.fail(at, "`${s}`: parameters exist only in a parameterized style (`style name(${s}: T) {{ … }}`)", .{ name, name });
        for (params) |*p| if (eq(p.name, name)) {
            p.used = true;
            return p;
        };
        var list: std.ArrayList(u8) = .empty;
        for (params, 0..) |p, i| {
            if (i != 0) try list.appendSlice(c.a, ", ");
            try @import("list_writer.zig").init(c.a, &list).print("${s}", .{p.name});
        }
        return c.fail(at, "unknown parameter `${s}` (declared: {s})", .{ name, list.items });
    }

    /// `$name` inside `{zig}`: check each against parameters (skip strings and comments); a bare
    /// identifier `t` (not a field `.t`) reads the theme.
    fn checkRawParams(c: *Compiler, raw: []const u8, at: usize) Error!void {
        var i: usize = 0;
        while (i < raw.len) : (i += 1) {
            if (skipZigLiteral(raw, i)) |end| {
                i = end;
                continue;
            }
            if (std.ascii.isAlphabetic(raw[i]) or raw[i] == '_') {
                var e = i + 1;
                while (e < raw.len and (std.ascii.isAlphanumeric(raw[e]) or raw[e] == '_')) e += 1;
                const after_dot = i > 0 and raw[i - 1] == '.';
                if (!after_dot and e - i == 1 and raw[i] == 't') c.uses_theme = true;
                i = e - 1;
                continue;
            }
            switch (raw[i]) {
                '$' => {
                    var e = i + 1;
                    while (e < raw.len and (std.ascii.isAlphanumeric(raw[e]) or raw[e] == '_')) e += 1;
                    if (e == i + 1) return c.fail(at + i, "`$` must be followed by a parameter name", .{});
                    _ = try c.useParam(raw[i + 1 .. e], at + i);
                    i = e - 1;
                },
                else => {},
            }
        }
    }

    /// `{zig}` source: replace `$name` with `args.name`, rest maps byte-by-byte to source
    fn emitRaw(c: *Compiler, raw: []const u8, at: usize) Error![]const u8 {
        if (std.mem.indexOfScalar(u8, raw, '$') == null) return c.rawMapped(raw, at);
        var out: std.ArrayList(u8) = .empty;
        var seg: usize = 0;
        var i: usize = 0;
        while (i < raw.len) : (i += 1) {
            if (skipZigLiteral(raw, i)) |end| {
                i = end;
                continue;
            }
            switch (raw[i]) {
                '$' => {
                    // checkRawParams already ensures `$` is followed by parameter name (same skip
                    // rules)
                    var e = i + 1;
                    while (e < raw.len and (std.ascii.isAlphanumeric(raw[e]) or raw[e] == '_')) e += 1;
                    if (i > seg) try out.appendSlice(c.a, try c.rawMapped(raw[seg..i], at + seg));
                    try @import("list_writer.zig").init(c.a, &out).print("args.{s}", .{raw[i + 1 .. e]});
                    seg = e;
                    i = e - 1;
                },
                else => {},
            }
        }
        if (seg < raw.len) try out.appendSlice(c.a, try c.rawMapped(raw[seg..], at + seg));
        return out.items;
    }

    /// `when` condition (`when` already read): `$flag`, `!$flag`, `$e = x`, `$e in (x, y)`, `{zig
    /// bool expression}`, joined with `&`.
    /// Read until `{` after condition (don't consume it).
    fn paramWhenCond(c: *Compiler) Error![]const u8 {
        var cond: std.ArrayList(u8) = .empty;
        var terms: usize = 0;
        var raw_terms: usize = 0;
        while (true) {
            terms += 1;
            var t = try c.next();
            if (t.tag == .lbrace) {
                const close = c.matchBrace(t.start, 0) orelse return c.fail(t.start, "unterminated `{{` expression", .{});
                const inner = c.src[t.end..close];
                const raw = std.mem.trim(u8, inner, " \t\r\n");
                if (raw.len == 0) return c.fail(t.start, "empty `{{}}` condition", .{});
                const at = t.end + (inner.len - std.mem.trimStart(u8, inner, " \t\r\n").len);
                try c.checkRawParams(raw, at);
                c.pos = close + 1;
                // Need parentheses only when `&`-joined with other conditions (see below)
                raw_terms += 1;
                try @import("list_writer.zig").init(c.a, &cond).print("({s})", .{try c.emitRaw(raw, at)});
            } else {
                var neg = false;
                if (t.tag == .bang) {
                    neg = true;
                    t = try c.next();
                }
                if (t.tag != .param) return c.fail(t.start, "a `when` condition is `$flag`, `!$flag`, `$param = option`, `$param in (a, b)` or `{{zig condition}}`", .{});
                const p = try c.useParam(c.src[t.start + 1 .. t.end], t.start);
                const nt = try c.peek();
                const is_in = nt.tag == .ident and eq(c.text(nt), "in");
                if (nt.tag == .eq or is_in) {
                    _ = try c.next();
                    if (neg) return c.fail(t.start, "`!` applies to a bool parameter; compare with another option instead", .{});
                    if (eq(p.ty, "bool") or p.optional()) return c.fail(t.start, "`${s} {s} …` compares an enum parameter, but `${s}` is `{s}`", .{ p.name, if (is_in) "in" else "=", p.name, p.ty });
                    if (nt.tag == .eq) {
                        const o = try c.expect(.ident, "an option name");
                        try @import("list_writer.zig").init(c.a, &cond).print("args.{s} == {s}", .{ p.name, try enumLiteral(c.a, c.text(o)) });
                    } else {
                        _ = try c.expect(.lparen, "`(` and the options");
                        try cond.append(c.a, '(');
                        var first = true;
                        while (true) {
                            const o = try c.expect(.ident, "an option name");
                            try @import("list_writer.zig").init(c.a, &cond).print("{s}args.{s} == {s}", .{ if (first) "" else " or ", p.name, try enumLiteral(c.a, c.text(o)) });
                            first = false;
                            const sep = try c.next();
                            if (sep.tag == .rparen) break;
                            if (sep.tag != .comma) return c.fail(sep.start, "expected `,` or `)`", .{});
                        }
                        try cond.append(c.a, ')');
                    }
                } else {
                    if (!eq(p.ty, "bool") and (p.knownNonOptional() or p.optional())) return c.fail(t.start, "`when ${s}` needs a bool parameter, but `${s}` is `{s}` (compare enums with `${s} = option`; test other values with `{{…}}`)", .{ p.name, p.name, p.ty, p.name });
                    try @import("list_writer.zig").init(c.a, &cond).print("{s}args.{s}", .{ if (neg) "!" else "", p.name });
                }
            }
            const sep = try c.peek();
            if (sep.tag == .lbrace) {
                // Only condition is `{zig}`: drop extra layer of parentheses
                if (terms == 1 and raw_terms == 1) return cond.items[1 .. cond.items.len - 1];
                return cond.items;
            }
            if (sep.tag != .amp) return c.fail(sep.start, "expected `&` or `{{` after the condition", .{});
            _ = try c.next();
            try cond.appendSlice(c.a, " and ");
        }
    }

    fn recipeDecl(c: *Compiler, out: *std.ArrayList(u8)) Error!void {
        const name_t = try c.expect(.ident, "a recipe name");
        _ = try c.fieldName(name_t, "recipe");
        c.slots = null;
        var t = try c.next();
        if (t.tag == .ident and eq(c.text(t), "slots")) {
            _ = try c.expect(.lparen, "`(` and the slot names");
            var slots: std.ArrayList([]const u8) = .empty;
            while (true) {
                const s = try c.expect(.ident, "a slot name");
                const slot = try c.fieldName(s, "slot");
                for (slots.items) |x| if (eq(x, slot)) return c.fail(s.start, "slot `{s}` is listed twice", .{slot});
                try slots.append(c.a, slot);
                const sep = try c.next();
                if (sep.tag == .rparen) break;
                if (sep.tag != .comma) return c.fail(sep.start, "expected `,` or `)`", .{});
            }
            c.slots = slots.items;
            t = try c.next();
        }
        if (t.tag != .lbrace) return c.fail(t.start, "expected `{{` and the recipe body", .{});

        var base: ?*Body = null;
        var dims: std.ArrayList(Dim) = .empty;
        var compounds: std.ArrayList(Compound) = .empty;
        while (true) {
            const kw = try c.next();
            if (kw.tag == .rbrace) break;
            if (kw.tag != .ident) return c.fail(kw.start, "expected `base`, `variant`, `flag` or `when`", .{});
            const word = c.text(kw);
            if (eq(word, "base")) {
                if (base != null) return c.fail(kw.start, "`base` is given twice", .{});
                _ = try c.expect(.lbrace, "`{`");
                const b = try c.a.create(Body);
                b.* = .{};
                try c.bodyUntilClose(b, c.topLevel());
                base = b;
            } else if (eq(word, "variant")) {
                try dims.append(c.a, try c.variantDim(dims.items));
            } else if (eq(word, "flag")) {
                try dims.append(c.a, try c.flagDim(dims.items));
            } else if (eq(word, "when")) {
                try c.compound(dims.items, &compounds);
            } else return c.fail(kw.start, "unknown recipe section `{s}` (expected base, variant, flag or when)", .{word});
        }

        if (c.capture_ir) {
            var ir_dims: std.ArrayList(ir.Dimension) = .empty;
            for (dims.items) |d| {
                var options: std.ArrayList(ir.Option) = .empty;
                for (d.options.items, d.bodies.items) |name, body|
                    try options.append(c.a, .{ .name = name, .layer = try body.lower(c.a) });
                try ir_dims.append(c.a, .{ .name = d.name, .flag = d.flag, .default = d.default, .options = options.items });
            }
            var ir_compounds: std.ArrayList(ir.Compound) = .empty;
            for (compounds.items) |compound_| {
                var predicates: std.ArrayList(ir.Predicate) = .empty;
                for (compound_.when.items) |pred|
                    try predicates.append(c.a, .{ .dimension = pred[0], .option = pred[1] });
                try ir_compounds.append(c.a, .{ .when = predicates.items, .layer = try compound_.body.lower(c.a) });
            }
            try c.ir_declarations.append(c.a, .{
                .name = c.text(name_t),
                .kind = if (c.slots != null) .slot_recipe else .recipe,
                .base = if (base) |b| try b.lower(c.a) else .{},
                .dimensions = ir_dims.items,
                .compounds = ir_compounds.items,
                .slots = if (c.slots) |sl| sl else &.{},
                .signature = if (c.slots != null) c.src[name_t.start..c.pos] else "",
                .offset = name_t.start,
            });
        }
        try out.appendSlice(c.a, "pub const ");
        try out.appendSlice(c.a, c.text(name_t));
        if (c.slots != null) {
            try out.appendSlice(c.a, " = ui.sva(.{");
        } else if (c.preview_path != null) {
            try out.appendSlice(c.a, " = ");
            try c.previewFactory(out, c.text(name_t), "previewCva");
            try out.appendSlice(c.a, ".{");
        } else try out.appendSlice(c.a, " = ui.cva(.{");
        if (c.slots) |slots| {
            try out.appendSlice(c.a, " .slots = .{");
            for (slots) |s| try @import("list_writer.zig").init(c.a, &out).print(" .{s},", .{s});
            try out.appendSlice(c.a, " },");
        }
        if (base) |b| {
            try out.appendSlice(c.a, " .base = ");
            try b.emit(c.a, out);
            try out.append(c.a, ',');
        }
        if (dims.items.len != 0) {
            try out.appendSlice(c.a, " .variants = .{");
            for (dims.items) |d| {
                try @import("list_writer.zig").init(c.a, &out).print(" .{s} = .{{", .{d.name});
                for (d.options.items, d.bodies.items) |o, b| {
                    try @import("list_writer.zig").init(c.a, &out).print(" .{s} = ", .{optionIdent(o)});
                    try b.emit(c.a, out);
                    try out.append(c.a, ',');
                }
                try out.appendSlice(c.a, " },");
            }
            try out.appendSlice(c.a, " }, .defaults = .{");
            for (dims.items) |d| try @import("list_writer.zig").init(c.a, &out).print(" .{s} = {s}{s},", .{ d.name, if (d.flag) "" else ".", if (d.flag) d.default else optionIdent(d.default) });
            try out.appendSlice(c.a, " },");
        }
        if (compounds.items.len != 0) {
            try out.appendSlice(c.a, " .compound = .{");
            for (compounds.items) |k| {
                try out.appendSlice(c.a, " .{ .when = .{");
                for (k.when.items) |w| try @import("list_writer.zig").init(c.a, &out).print(" .{s} = {s},", .{ w[0], w[1] });
                try out.appendSlice(c.a, " }, .style = ");
                try k.body.emit(c.a, out);
                try out.appendSlice(c.a, " },");
            }
            try out.appendSlice(c.a, " },");
        }
        try out.appendSlice(c.a, " });");
    }

    fn findDim(dims: []const Dim, name: []const u8) ?*const Dim {
        for (dims) |*d| if (eq(d.name, name)) return d;
        return null;
    }

    fn variantDim(c: *Compiler, dims: []const Dim) Error!Dim {
        const name_t = try c.expect(.ident, "a variant name");
        const dim_name = try c.fieldName(name_t, "variant");
        if (findDim(dims, dim_name) != null) return c.fail(name_t.start, "dimension `{s}` is declared twice", .{dim_name});
        var d: Dim = .{ .name = dim_name, .flag = false, .default = "", .at = name_t.start };
        var default_t: ?Tok = null;
        var t = try c.next();
        if (t.tag == .eq) {
            default_t = try c.expect(.ident, "the default option");
            t = try c.next();
        }
        if (t.tag != .lbrace) return c.fail(t.start, "expected `{{` and the options", .{});
        while (true) {
            const o = try c.next();
            if (o.tag == .rbrace) break;
            if (o.tag != .ident) return c.fail(o.start, "expected an option name", .{});
            // Option name can match Zig keyword (`.@"error"` in public enum); generate as @"error"
            if (std.zig.Token.getKeyword(c.text(o)) == null) _ = try c.fieldName(o, "option");
            for (d.options.items) |x| if (eq(x, c.text(o))) return c.fail(o.start, "option `{s}` is given twice", .{x});
            _ = try c.expect(.lbrace, "`{`");
            const b = try c.a.create(Body);
            b.* = .{};
            try c.bodyUntilClose(b, c.topLevel());
            try d.options.append(c.a, c.text(o));
            try d.bodies.append(c.a, b);
        }
        if (d.options.items.len == 0) return c.fail(name_t.start, "variant `{s}` has no options", .{d.name});
        if (default_t) |dt| {
            const want = c.text(dt);
            for (d.options.items) |x| {
                if (eq(x, want)) break;
            } else return c.fail(dt.start, "default `{s}` is not an option of `{s}`", .{ want, d.name });
            d.default = want;
        } else d.default = d.options.items[0];
        return d;
    }

    fn flagDim(c: *Compiler, dims: []const Dim) Error!Dim {
        const name_t = try c.expect(.ident, "a flag name");
        const flag_name = try c.fieldName(name_t, "flag");
        if (findDim(dims, flag_name) != null) return c.fail(name_t.start, "dimension `{s}` is declared twice", .{flag_name});
        var d: Dim = .{ .name = flag_name, .flag = true, .default = "false", .at = name_t.start };
        var t = try c.next();
        if (t.tag == .eq) {
            const v = try c.expect(.ident, "`true` or `false`");
            if (!eq(c.text(v), "true") and !eq(c.text(v), "false")) return c.fail(v.start, "a flag defaults to `true` or `false`", .{});
            d.default = c.text(v);
            t = try c.next();
        }
        const on = try c.a.create(Body);
        on.* = .{};
        if (t.tag == .lbrace) {
            try c.bodyUntilClose(on, c.topLevel());
        } else if (t.tag != .semi) return c.fail(t.start, "expected `;` or `{{`", .{});
        const off = try c.a.create(Body);
        off.* = .{};
        // `flag x { on } else { off }`: block when off (same level as on block, mutually exclusive
        // by dimension value)
        if (t.tag == .lbrace) {
            const nt = try c.peek();
            if (nt.tag == .ident and eq(c.text(nt), "else")) {
                _ = try c.next();
                _ = try c.expect(.lbrace, "`{` after `else`");
                try c.bodyUntilClose(off, c.topLevel());
            }
        }
        try d.options.append(c.a, "false");
        try d.bodies.append(c.a, off);
        try d.options.append(c.a, "true");
        try d.bodies.append(c.a, on);
        return d;
    }

    /// `when a & !b & c = x & d in (y, z) { ... }`: `in` expands into multiple compound rules
    fn compound(c: *Compiler, dims: []const Dim, out: *std.ArrayList(Compound)) Error!void {
        const Alt = struct { dim: []const u8, values: [][]const u8 };
        var terms: std.ArrayList(Alt) = .empty;
        // A short source can otherwise expand exponentially, including during LSP edits.
        // Bound the total per recipe before allocating or emitting the Cartesian product.
        const max_compounds = 4096;
        var combinations: usize = 1;
        while (true) {
            var t = try c.next();
            var negate = false;
            if (t.tag == .bang) {
                negate = true;
                t = try c.next();
            }
            if (t.tag != .ident) return c.fail(t.start, "expected a dimension name", .{});
            const name = c.text(t);
            const d = findDim(dims, name) orelse return c.fail(t.start, "`{s}` is not a declared variant or flag (declare it before the `when`)", .{name});
            for (terms.items) |x| if (eq(x.dim, name)) return c.fail(t.start, "`{s}` appears twice in one condition", .{name});
            var values: std.ArrayList([]const u8) = .empty;
            const after = try c.peek();
            if (d.flag) {
                if (after.tag == .eq or (after.tag == .ident and eq(c.text(after), "in"))) return c.fail(after.start, "`{s}` is a flag: write `{s}` or `!{s}`", .{ name, name, name });
                try values.append(c.a, if (negate) "false" else "true");
            } else {
                if (negate) return c.fail(t.start, "`!` applies to flags; for a variant write `{s} = option`", .{name});
                const op = try c.next();
                if (op.tag == .eq) {
                    const v = try c.expect(.ident, "an option name");
                    try values.append(c.a, try c.checkOption(d, v));
                } else if (op.tag == .ident and eq(c.text(op), "in")) {
                    _ = try c.expect(.lparen, "`(`");
                    while (true) {
                        const v = try c.expect(.ident, "an option name");
                        try values.append(c.a, try c.checkOption(d, v));
                        const sep = try c.next();
                        if (sep.tag == .rparen) break;
                        if (sep.tag != .comma) return c.fail(sep.start, "expected `,` or `)`", .{});
                    }
                } else return c.fail(op.start, "a variant in a condition needs `= option` or `in (a, b)`", .{});
            }
            if (combinations > max_compounds / values.items.len)
                return c.fail(t.start, "recipe `when` expansion exceeds the limit of {d} compound rules (reduce `in` alternatives or split the recipe)", .{max_compounds});
            combinations *= values.items.len;
            if (combinations > max_compounds - out.items.len)
                return c.fail(t.start, "recipe `when` expansion exceeds the limit of {d} compound rules (reduce `in` alternatives or split the recipe)", .{max_compounds});
            try terms.append(c.a, .{ .dim = name, .values = values.items });
            const sep = try c.next();
            if (sep.tag == .lbrace) break;
            if (sep.tag != .amp) return c.fail(sep.start, "expected `&` or `{{`", .{});
        }
        const body = try c.a.create(Body);
        body.* = .{};
        try c.bodyUntilClose(body, c.topLevel());
        // Cartesian product: one rule per value of each `in` (same style block shared)
        var idx = try c.a.alloc(usize, terms.items.len);
        @memset(idx, 0);
        while (true) {
            var k: Compound = .{ .body = body };
            for (terms.items, idx) |term, i| {
                const v = term.values[i];
                const lit = if (eq(v, "true") or eq(v, "false")) v else try std.fmt.allocPrint(c.a, ".{s}", .{optionIdent(v)});
                try k.when.append(c.a, .{ term.dim, lit });
            }
            try out.append(c.a, k);
            var j: usize = terms.items.len;
            while (j > 0) {
                j -= 1;
                idx[j] += 1;
                if (idx[j] < terms.items[j].values.len) break;
                idx[j] = 0;
            } else break;
        }
    }

    fn checkOption(c: *Compiler, d: *const Dim, v: Tok) Error![]const u8 {
        const name = c.text(v);
        for (d.options.items) |o| if (eq(o, name)) return name;
        return c.fail(v.start, "`{s}` is not an option of `{s}`", .{ name, d.name });
    }

    // -- Block --

    /// Read until matching `}` (left brace already read), merge contents into body
    fn bodyUntilClose(c: *Compiler, body: *Body, level: Level) Error!void {
        while (true) {
            const t = try c.next();
            switch (t.tag) {
                .rbrace => return,
                .eof => return c.fail(t.start, "unterminated block (missing `}}`)", .{}),
                .colon => {
                    if (c.params != null) return c.fail(t.start, "a parameterized style is a pure function of its parameters; interactive states (`:hover` …) belong in a recipe or a plain style on the same node", .{});
                    if (c.first_state_at == null) c.first_state_at = t.start;
                    const cond = try c.expect(.ident, "a condition after `:`");
                    const name = c.text(cond);
                    for (conditions) |x| {
                        if (eq(x, name)) break;
                    } else return c.fail(cond.start, "unknown condition `:{s}` (available: :hover :active :focus :focus-visible :selected :expanded :invalid :disabled)", .{name});
                    if (level == .slots) return c.fail(cond.start, "in a slotted recipe, conditions go inside a slot block", .{});
                    _ = try c.expect(.lbrace, "`{`");
                    const key = try std.fmt.allocPrint(c.a, "_{s}", .{try c.snake(name)});
                    try c.bodyUntilClose(try body.child(c.a, key), .flat);
                },
                .ident => {
                    const after = try c.peek();
                    const name = c.text(t);
                    if (c.params != null and eq(name, "when") and (after.tag == .param or after.tag == .bang or after.tag == .lbrace)) {
                        const whens = c.param_whens orelse return c.fail(t.start, "`when` blocks do not nest (combine conditions with `&`)", .{});
                        const cond = try c.paramWhenCond();
                        _ = try c.expect(.lbrace, "`{`");
                        const blk = try c.a.create(Body);
                        blk.* = .{};
                        c.param_whens = null;
                        defer c.param_whens = whens;
                        try c.bodyUntilClose(blk, .flat);
                        try whens.append(c.a, .{ .cond = cond, .body = blk });
                        continue;
                    }
                    switch (after.tag) {
                        .colon => {
                            if (level == .slots) return c.fail(t.start, "in a slotted recipe, properties go inside a slot block (`slot {{ {s}: …; }}`)", .{name});
                            _ = try c.next();
                            try c.declaration(body, t);
                        },
                        .lbrace => {
                            _ = try c.next();
                            const slots = c.slots orelse return c.fail(t.start, "`{s} {{` opens a slot block, but this recipe has no slots (declare `recipe Name slots(...)`)", .{name});
                            if (level != .slots) return c.fail(t.start, "slot blocks do not nest", .{});
                            for (slots) |sl| {
                                if (eq(sl, name)) break;
                            } else return c.fail(t.start, "`{s}` is not a slot of this recipe", .{name});
                            try c.bodyUntilClose(try body.child(c.a, name), .flat);
                        },
                        .lparen => {
                            _ = try c.next();
                            try c.expand(body, t, level);
                        },
                        else => return c.fail(after.start, "expected `:` after the property `{s}`", .{name}),
                    }
                },
                else => return c.fail(t.start, "expected a property, a `:condition {{ }}` block or a mixin call", .{}),
            }
        }
    }

    /// `name(args);`: expand mixin's block here, parameters replaced by call-site values by name
    fn expand(c: *Compiler, body: *Body, name_t: Tok, level: Level) Error!void {
        const name = c.text(name_t);
        const m = c.mixins.get(name) orelse return c.fail(name_t.start, "unknown mixin `{s}`", .{name});
        var args: std.ArrayList(Val) = .empty;
        if ((try c.peek()).tag == .rparen) {
            _ = try c.next();
        } else while (true) {
            try args.append(c.a, try c.value());
            const sep = try c.next();
            if (sep.tag == .rparen) break;
            if (sep.tag != .comma) return c.fail(sep.start, "expected `,` or `)`", .{});
        }
        _ = try c.expect(.semi, "`;` after the mixin call");
        if (args.items.len != m.params.len) return c.fail(name_t.start, "mixin `{s}` takes {d} argument(s), got {d}", .{ name, m.params.len, args.items.len });
        if (c.depth >= 16) return c.fail(name_t.start, "mixin expansion is nested too deeply (recursive mixin?)", .{});
        var map: std.StringHashMapUnmanaged(Val) = .empty;
        for (m.params, args.items) |p, v| try map.put(c.a, p, v);
        const save_pos = c.pos;
        const save_subst = c.subst;
        c.pos = m.body_start;
        c.subst = &map;
        c.depth += 1;
        defer {
            c.pos = save_pos;
            c.subst = save_subst;
            c.depth -= 1;
        }
        try c.bodyUntilClose(body, level);
    }

    // -- Property --

    fn declaration(c: *Compiler, body: *Body, name_t: Tok) Error!void {
        const prop = c.text(name_t);
        if (eq(prop, "transition")) {
            if (c.params != null) return c.fail(name_t.start, "transitions are not supported in a parameterized style; declare them in a plain style or recipe on the same node", .{});
            if (c.first_transition_at == null) c.first_transition_at = name_t.start;
            // Entire source is transition description (`background 150ms ease-out, opacity 100ms`),
            // can span lines; whitespace folded to single space.
            // Misspelled property/duration/easing reported by ui.transition at compile time (mapped
            // to this line)
            c.skipSpace();
            const s = c.pos;
            while (c.pos < c.src.len and c.src[c.pos] != ';' and c.src[c.pos] != '{' and c.src[c.pos] != '}') c.pos += 1;
            if (c.pos < c.src.len and c.src[c.pos] == '{') return c.fail(s, "a transition is plain text like `background 150ms ease-out`", .{});
            if (c.pos >= c.src.len or c.src[c.pos] != ';') return c.fail(s, "expected `;` after the transition", .{});
            const seg = c.src[s..c.pos];
            c.pos += 1;
            if (std.mem.indexOfAny(u8, seg, "\"\\") != null) return c.fail(s, "a transition is plain text like `background 150ms ease-out`", .{});
            var raw: std.ArrayList(u8) = .empty;
            var words = std.mem.tokenizeAny(u8, seg, " \t\r\n");
            while (words.next()) |w| {
                if (raw.items.len != 0 and raw.items[raw.items.len - 1] != ' ' and w[0] != ',') try raw.append(c.a, ' ');
                try raw.appendSlice(c.a, w);
            }
            if (raw.items.len == 0) return c.fail(s, "empty transition", .{});
            if (c.capture_ir) try body.record(c.a, .{ .name = "transition", .value = .{ .name = raw.items }, .offset = name_t.start });
            return c.setAt(body, name_t, "transition", try std.fmt.allocPrint(c.a, "ui.transition(\"{s}\")", .{raw.items}));
        }
        var vals: std.ArrayList(Val) = .empty;
        // `shadow: a, b`: comma-separated multi-layer shadows, record start of each
        var layers: std.ArrayList(usize) = .empty;
        while ((try c.peek()).tag != .semi) {
            if ((try c.peek()).tag == .rbrace or (try c.peek()).tag == .eof) return c.fail(name_t.start, "expected `;` after `{s}`", .{prop});
            if ((try c.peek()).tag == .comma and eq(prop, "shadow")) {
                const comma = try c.next();
                if (vals.items.len == (if (layers.items.len == 0) 0 else layers.items[layers.items.len - 1])) return c.fail(comma.start, "empty shadow layer", .{});
                try layers.append(c.a, vals.items.len);
                continue;
            }
            try vals.append(c.a, try c.value());
        }
        _ = try c.next();
        if (vals.items.len == 0) return c.fail(name_t.start, "`{s}` has no value", .{prop});
        const field = try c.snake(prop);
        if (eq(field, "flex_basis")) for (vals.items) |v| try c.validateFlexBasis(v, name_t.start);
        if (c.capture_ir) {
            const values = try c.a.alloc(ir.Value, vals.items.len);
            for (vals.items, 0..) |v, i| values[i] = try c.lowerValue(v);
            // A comma divides shadow layers; retain that grouping in the IR.
            const ir_value: ir.Value = if (eq(field, "shadow") and layers.items.len != 0) blk: {
                const stack = try c.a.alloc(ir.Value, layers.items.len + 1);
                var start: usize = 0;
                for (stack, 0..) |*item, i| {
                    const end = if (i < layers.items.len) layers.items[i] else values.len;
                    item.* = if (end - start == 1) values[start] else .{ .list = values[start..end] };
                    start = end;
                }
                break :blk .{ .call = .{ .name = "shadow_stack", .args = stack } };
            } else if (values.len == 1) values[0] else .{ .list = values };
            if (eq(field, "border")) {
                // Match Zig lowering's sparse writes: a later width-only shorthand
                // preserves a color declared by an earlier border shorthand.
                if (values.len > 0) try body.record(c.a, .{ .name = "border_width", .value = values[0], .offset = name_t.start });
                if (values.len == 2) try body.record(c.a, .{ .name = "border_color", .value = values[1], .offset = name_t.start });
            } else try body.record(c.a, .{ .name = field, .value = ir_value, .offset = name_t.start });
        }
        _ = schema.prop(field) orelse {
            if (suggest(field)) |near| return c.fail(name_t.start, "`{s}` is not a style property (did you mean `{s}`?)", .{ prop, try kebab(c.a, near) });
            return c.fail(name_t.start, "`{s}` is not a style property", .{prop});
        };
        if (eq(field, "padding") or eq(field, "margin")) {
            const v = vals.items;
            const expr = switch (v.len) {
                1 => try c.emitVal(v[0], field, false),
                2 => try std.fmt.allocPrint(c.a, ".{{ .y = {s}, .x = {s} }}", .{ try c.emitVal(v[0], field, false), try c.emitVal(v[1], field, false) }),
                4 => try std.fmt.allocPrint(c.a, ".{{ .top = {s}, .right = {s}, .bottom = {s}, .left = {s} }}", .{ try c.emitVal(v[0], field, false), try c.emitVal(v[1], field, false), try c.emitVal(v[2], field, false), try c.emitVal(v[3], field, false) }),
                else => return c.fail(name_t.start, "`{s}` takes 1, 2 (vertical horizontal) or 4 (top right bottom left) values", .{prop}),
            };
            return c.setAt(body, name_t, field, expr);
        }
        if (eq(field, "shadow") and layers.items.len != 0) {
            // Multi-layer: later painted on bottom (CSS order), write to shadows; single layer
            // still write shadow
            if (vals.items.len == layers.items[layers.items.len - 1]) return c.fail(name_t.start, "empty shadow layer", .{});
            var list: std.ArrayList(u8) = .empty;
            try list.appendSlice(c.a, ".{");
            var from: usize = 0;
            for (0..layers.items.len + 1) |i| {
                const to = if (i < layers.items.len) layers.items[i] else vals.items.len;
                try @import("list_writer.zig").init(c.a, &list).print(" {s},", .{try c.shadowExpr(vals.items[from..to], name_t)});
                from = to;
            }
            try list.appendSlice(c.a, " }");
            try c.setAt(body, name_t, "shadows", list.items);
            return;
        }
        if (eq(field, "shadow") and vals.items.len > 1) return c.setAt(body, name_t, "shadow", try c.shadowExpr(vals.items, name_t));
        if (eq(field, "border")) {
            const v = vals.items;
            if (v.len > 2) return c.fail(name_t.start, "`border` takes a width and an optional color", .{});
            try c.setAt(body, name_t, "border_width", try c.emitVal(v[0], "border_width", false));
            if (v.len == 2) try c.setAt(body, name_t, "border_color", try c.emitVal(v[1], "border_color", false));
            return;
        }
        if (vals.items.len != 1) return c.fail(name_t.start, "`{s}` takes one value", .{prop});
        return c.setAt(body, name_t, field, try c.emitVal(vals.items[0], field, false));
    }

    /// Write one property; generated value maps entire property name back to source: Zig compile
    /// errors (misspelled token, type mismatch) point to this line, not declaration start
    fn setAt(c: *Compiler, body: *Body, name_t: Tok, key: []const u8, expr: []const u8) Error!void {
        // Both fields represent the YSS `shadow` property. Keep only the latest
        // declaration, including declarations expanded from mixins.
        const other: ?[]const u8 = if (eq(key, "shadow")) "shadows" else if (eq(key, "shadows")) "shadow" else null;
        if (other) |name| if (body.find(name)) |i| {
            _ = body.keys.orderedRemove(i);
            _ = body.vals.orderedRemove(i);
        };
        try body.setExpr(c.a, key, try std.fmt.allocPrint(c.a, "{c}{d}{c}{s}{c}", .{ compiler.mark_point, name_t.start, compiler.mark_text, expr, compiler.mark_close }));
    }

    /// One shadow layer: token (`md`) or `x y blur [spread] color` (color can be token, #hex,
    /// rgba(), or mix())
    fn shadowExpr(c: *Compiler, v: []const Val, name_t: Tok) Error![]const u8 {
        if (v.len == 1) return c.emitVal(v[0], "shadow", false);
        if (v.len != 4 and v.len != 5) return c.fail(name_t.start, "`shadow` is a token (`shadow: md`) or `x y blur [spread] color`; separate layers with `,`", .{});
        for (v[0 .. v.len - 1]) |x| if (x != .num) return c.fail(name_t.start, "`shadow`: x, y, blur and spread are numbers", .{});
        const spread = if (v.len == 5) v[3].num else "0";
        return std.fmt.allocPrint(c.a, ".{{ .offset_x = {s}, .offset_y = {s}, .blur = {s}, .spread = {s}, .color = {s} }}", .{ v[0].num, v[1].num, v[2].num, spread, try c.emitVal(v[v.len - 1], "background", false) });
    }

    /// Static check of name value: only take enum/bool fields, name must be one of its possible
    /// values (token name is per design system, left for Zig compile-time lookup)
    fn checkName(c: *Compiler, name: []const u8, at: usize, field: []const u8) Error!void {
        const p = schema.prop(field) orelse return;
        if (p.category.len != 0 or p.values.len == 0) return;
        const want = try c.snake(name);
        for (p.values) |v| if (eq(v, want)) return;
        var list: std.ArrayList(u8) = .empty;
        for (p.values, 0..) |v, i| {
            if (i != 0) try list.appendSlice(c.a, ", ");
            try list.appendSlice(c.a, try kebab(c.a, v));
        }
        return c.fail(at, "`{s}` is not a value of `{s}` (expected {s})", .{ name, try kebab(c.a, field), list.items });
    }

    fn value(c: *Compiler) Error!Val {
        const t = try c.next();
        switch (t.tag) {
            .number => {
                const n = c.text(t);
                const digits = if (n[0] == '-') n[1..] else n;
                if (std.mem.count(u8, digits, ".") > 1 or digits.len == 0 or digits[digits.len - 1] == '.')
                    return c.fail(t.start, "malformed number `{s}`", .{n});
                if (digits.len > 1 and digits[0] == '0' and digits[1] != '.') return c.fail(t.start, "malformed number `{s}` (no leading zeros)", .{n});
                // `.5` -> `0.5` (Zig doesn't accept leading dot)
                if (digits[0] == '.') return .{ .num = try std.fmt.allocPrint(c.a, "{s}0{s}", .{ if (n[0] == '-') "-" else "", digits }) };
                return .{ .num = n };
            },
            .hash => {
                const hex = c.src[t.start + 1 .. t.end];
                if (hex.len != 6 and hex.len != 8) return c.fail(t.start, "colors are #rrggbb or #rrggbbaa", .{});
                for (hex) |ch| if (!std.ascii.isHex(ch)) return c.fail(t.start, "colors are #rrggbb or #rrggbbaa", .{});
                return .{ .hex = hex };
            },
            .lbrace => {
                // {zig expression}: embed as-is (paired braces, recognize strings and comments)
                const close = c.matchBrace(t.start, 0) orelse return c.fail(t.start, "unterminated `{{` expression", .{});
                const inner = c.src[t.end..close];
                const raw = std.mem.trim(u8, inner, " \t\r\n");
                c.pos = close + 1;
                if (raw.len == 0) return c.fail(t.start, "empty `{{}}` expression", .{});
                const at = t.end + (inner.len - std.mem.trimStart(u8, inner, " \t\r\n").len);
                try c.checkRawParams(raw, at);
                return .{ .raw = .{ .text = raw, .at = at } };
            },
            .ident => {
                const name = c.text(t);
                if ((try c.peek()).tag == .lparen) {
                    _ = try c.next();
                    var args: std.ArrayList(Val) = .empty;
                    while (true) {
                        try args.append(c.a, try c.value());
                        const sep = try c.next();
                        if (sep.tag == .rparen) break;
                        if (sep.tag != .comma) return c.fail(sep.start, "expected `,` or `)`", .{});
                    }
                    if (eq(name, "rgb") or eq(name, "rgba")) {
                        const want: usize = if (eq(name, "rgb")) 3 else 4;
                        if (args.items.len != want) return c.fail(t.start, "{s} takes {d} numbers: r, g, b 0..255{s}", .{ name, want, if (want == 4) ", alpha 0..1" else "" });
                        for (args.items) |x| if (x != .num) return c.fail(t.start, "{s} takes numbers", .{name});
                        return .{ .call = .{ .name = name, .args = args.items, .at = t.start } };
                    }
                    if (!eq(name, "mix")) return c.fail(t.start, "unknown function `{s}` (values support mix(a, b, weight), rgb(r, g, b), rgba(r, g, b, a))", .{name});
                    if (args.items.len != 3) return c.fail(t.start, "mix takes (color, color, weight)", .{});
                    return .{ .call = .{ .name = name, .args = args.items, .at = t.start } };
                }
                if (c.subst) |m| if (m.get(name)) |v| return v;
                return .{ .ident = .{ .name = name, .at = t.start } };
            },
            .param => {
                const p = try c.useParam(c.src[t.start + 1 .. t.end], t.start);
                if ((try c.peek()).tag != .qq) return .{ .param = .{ .name = p.name, .at = t.start } };
                const qq = try c.next();
                if (!p.optional() and p.knownNonOptional()) return c.fail(qq.start, "`??` gives a fallback for a null parameter, but `${s}` is `{s}` (not optional)", .{ p.name, p.ty });
                const fb = try c.a.create(Val);
                fb.* = try c.value();
                switch (fb.*) {
                    .param, .or_else => return c.fail(qq.end, "the fallback after `??` is a plain value (a token, number, color or `{{zig}}`)", .{}),
                    else => {},
                }
                return .{ .or_else = .{ .name = p.name, .fallback = fb, .at = t.start } };
            },
            else => return c.fail(t.start, "expected a value", .{}),
        }
    }

    fn validateFlexBasis(c: *Compiler, v: Val, at: usize) Error!void {
        switch (v) {
            .num => |n| {
                const basis_value = std.fmt.parseFloat(f32, n) catch return c.fail(at, "invalid flex-basis `{s}`", .{n});
                if (!std.math.isFinite(basis_value) or (basis_value < 0 and basis_value != -1 and basis_value != -2))
                    return c.fail(at, "flex-basis must be nonnegative, auto (-1), or content (-2)", .{});
            },
            .or_else => |o| try c.validateFlexBasis(o.fallback.*, o.at),
            else => {}, // parameters/raw Zig are checked by their typed consumer
        }
    }

    fn lowerValue(c: *Compiler, v: Val) Error!ir.Value {
        return switch (v) {
            .num => |n| .{ .number = std.fmt.parseFloat(f64, n) catch return c.fail(c.pos, "invalid numeric value `{s}`", .{n}) },
            .ident => |id| .{ .name = id.name },
            .hex => |hex| .{ .hex = hex },
            .raw => |raw| .{ .frozen = try std.fmt.allocPrint(c.a, "raw:{s}", .{raw.text}) },
            .param => |param| .{ .frozen = try std.fmt.allocPrint(c.a, "param:{s}", .{param.name}) },
            .or_else => |o| .{ .frozen = try std.fmt.allocPrint(c.a, "or_else:{s}:{s}", .{ o.name, try c.emitVal(o.fallback.*, "background", false) }) },
            .call => |call| blk: {
                const args = try c.a.alloc(ir.Value, call.args.len);
                for (call.args, 0..) |arg, i| args[i] = try c.lowerValue(arg);
                break :blk .{ .call = .{ .name = call.name, .args = args } };
            },
        };
    }

    fn emitVal(c: *Compiler, v: Val, field: []const u8, in_mix: bool) Error![]const u8 {
        return switch (v) {
            .num => |n| n,
            .raw => |r| try c.emitRaw(r.text, r.at),
            .param => |p| try std.fmt.allocPrint(c.a, "args.{s}", .{p.name}),
            .or_else => |o| blk: {
                if (in_mix) return c.fail(o.at, "`??` cannot be used inside mix(); give the parameter a default instead", .{});
                break :blk try std.fmt.allocPrint(c.a, "ui.orElse(args.{s}, {s})", .{ o.name, try c.emitVal(o.fallback.*, field, false) });
            },
            .hex => |h| if (h.len == 6)
                try std.fmt.allocPrint(c.a, "ui.Color.hex(0x{s})", .{h})
            else
                try std.fmt.allocPrint(c.a, "ui.Color.rgba(0x{s}, 0x{s}, 0x{s}, 0x{s})", .{ h[0..2], h[2..4], h[4..6], h[6..8] }),
            .ident => |id| blk: {
                const name = id.name;
                if (eq(field, "flex_basis")) {
                    try c.checkName(name, id.at, field);
                    break :blk try std.fmt.allocPrint(c.a, "ui.FlexBasis.{s}", .{name});
                }
                if (!in_mix) try c.checkName(id.name, id.at, field);
                if (eq(name, "transparent")) break :blk "ui.Color.TRANSPARENT";
                if (eq(name, "true") or eq(name, "false")) break :blk name;
                // Token name passed to ui.css as-is (prefer original, else `-` to `_`): design
                // systems allow names like `text-hairline`, `2xl`
                if (in_mix) break :blk try std.fmt.allocPrint(c.a, "ui.tokenRef(.color, \"{s}\")", .{name});
                if (eq(name, "grow") and isSizing(field)) break :blk ".{ .grow = .{} }";
                // fit/fill for width/height are size keywords, not tokens
                if (isSizing(field) and (eq(name, "fit") or eq(name, "fill"))) break :blk try std.fmt.allocPrint(c.a, ".{s}", .{name});
                // Token referenced by name in generated code line: misspelled token name compiles
                // error here, maps back to .yss property line.
                // (If written as enum literal, error is deep in ui.css, reference chain doesn't
                // show twin)
                if (isTokenField(field)) break :blk try std.fmt.allocPrint(c.a, "ui.tokenRef(.{s}, \"{s}\")", .{ schema.prop(field).?.category, name });
                break :blk try std.fmt.allocPrint(c.a, ".{s}", .{try c.snake(name)});
            },
            .call => |call| if (eq(call.name, "rgb") or eq(call.name, "rgba")) blk: {
                // rgb(r, g, b) / rgba(r, g, b, a): channels 0..255 integer, alpha 0..1 (like CSS),
                // converted to 0..255 at compile time
                var ch: [4]u8 = .{ 0, 0, 0, 255 };
                for (call.args, 0..) |x, i| {
                    const f = std.fmt.parseFloat(f64, x.num) catch return c.fail(call.at, "{s} takes numbers", .{call.name});
                    if (i < 3) {
                        if (f < 0 or f > 255 or @floor(f) != f) return c.fail(call.at, "{s}: r, g, b are whole numbers 0..255", .{call.name});
                        ch[i] = @intFromFloat(f);
                    } else {
                        if (f < 0 or f > 1) return c.fail(call.at, "rgba: alpha is 0..1", .{});
                        ch[3] = @intFromFloat(@round(f * 255));
                    }
                }
                break :blk try std.fmt.allocPrint(c.a, "ui.Color.rgba({d}, {d}, {d}, {d})", .{ ch[0], ch[1], ch[2], ch[3] });
            } else blk: {
                // mix(a, b, weight): color operands are token references or color values, weight is
                // number
                const w = call.args[2];
                if (w != .num) return c.fail(call.at, "mix weight must be a number", .{});
                const wv = std.fmt.parseFloat(f32, w.num) catch return c.fail(call.at, "mix weight must be a number", .{});
                if (wv < 0 or wv > 1) return c.fail(call.at, "mix weight must be within 0..1", .{});
                break :blk try std.fmt.allocPrint(c.a, "ui.mix({s}, {s}, {s})", .{ try c.emitVal(call.args[0], field, true), try c.emitVal(call.args[1], field, true), w.num });
            },
        };
    }
};

/// camelCase -> snake_case (naming suggestion)
fn snakeOf(a: Allocator, name: []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    for (name, 0..) |ch, i| {
        if (std.ascii.isUpper(ch)) {
            if (i != 0) try out.append(a, '_');
            try out.append(a, std.ascii.toLower(ch));
        } else try out.append(a, ch);
    }
    return out.items;
}

/// Misspelled property name: nearest with edit distance <= 2
fn suggest(field: []const u8) ?[]const u8 {
    var best: ?[]const u8 = null;
    var best_d: usize = 3;
    for (&schema.props) |*p| {
        const d = editDistance(field, p.name);
        if (d < best_d) {
            best_d = d;
            best = p.name;
        }
    }
    return best;
}

fn editDistance(a: []const u8, b: []const u8) usize {
    if (b.len > 63) return 99;
    var prev: [64]usize = undefined;
    for (prev[0 .. b.len + 1], 0..) |*x, j| x.* = j;
    for (a, 0..) |ca, i| {
        var cur: [64]usize = undefined;
        cur[0] = i + 1;
        for (b, 0..) |cb, j| cur[j + 1] = @min(prev[j] + @intFromBool(ca != cb), @min(prev[j + 1] + 1, cur[j] + 1));
        @memcpy(prev[0 .. b.len + 1], cur[0 .. b.len + 1]);
    }
    return prev[b.len];
}

/// snake_case -> .yss hyphenated form
pub fn kebab(a: Allocator, name: []const u8) ![]const u8 {
    const out = try a.dupe(u8, name);
    for (out) |*ch| if (ch.* == '_') {
        ch.* = '-';
    };
    return out;
}

/// Top-level DSL declaration. start: position in source (includes pub prefix); keyword:
/// recipe/style/mixin keyword;
/// open: `{` of declaration body; end: matching `}` after (err states reason if no body or
/// unclosed; editor analysis treats end as file end).
const Decl = struct { kind: Symbol.Kind, start: usize, keyword: usize, open: ?usize, end: usize };
const Found = struct { decls: []Decl, err: ?Diagnostic };

/// Scan top level: copy Zig as-is, statement-start recipe/style/mixin is DSL declaration (to
/// matching `}`, using DSL's own boundary rules)
fn findDecls(a: Allocator, src: []const u8) Error!Found {
    const zsrc = try a.dupeSentinel(u8, src, 0);
    var decls: std.ArrayList(Decl) = .empty;
    var err: ?Diagnostic = null;
    var z = std.zig.Tokenizer.init(zsrc);
    var depth: usize = 0;
    var at_stmt = true;
    // Statement-start `pub`: if followed by DSL declaration, declaration starts from pub (recipes
    // generate `pub const` anyway)
    var pub_start: ?usize = null;
    while (true) {
        const t = z.next();
        if (t.tag == .keyword_pub and depth == 0 and at_stmt) {
            pub_start = t.loc.start;
            continue;
        }
        const pending_pub = pub_start;
        pub_start = null;
        switch (t.tag) {
            .eof => break,
            .l_brace, .l_paren, .l_bracket => depth += 1,
            .r_brace, .r_paren, .r_bracket => {
                depth -|= 1;
                if (depth == 0 and t.tag == .r_brace) at_stmt = true;
                continue;
            },
            .semicolon => if (depth == 0) {
                at_stmt = true;
                continue;
            },
            .doc_comment, .container_doc_comment => continue,
            .identifier => if (depth == 0 and at_stmt) {
                const word = src[t.loc.start..t.loc.end];
                const kind: ?Symbol.Kind = if (eq(word, "recipe")) .recipe else if (eq(word, "style")) .style else if (eq(word, "mixin")) .mixin else null;
                if (kind) |k| {
                    // Parameter list (`style name($p: T = .{...})`, `mixin name(a)`) can have
                    // braces: find declaration body's `{` after matching `)`
                    const open = std.mem.indexOfScalarPos(u8, src, headerEnd(src, t.loc.end), '{');
                    var end = src.len;
                    if (open) |o| {
                        if (matchBraceIn(src, o, 0)) |close| {
                            end = close + 1;
                        } else if (err == null) err = .{ .offset = o, .message = "unterminated declaration (missing `}`)" };
                    } else if (err == null) err = .{ .offset = t.loc.end, .message = "expected `{` and the declaration body" };
                    try decls.append(a, .{ .kind = k, .start = pending_pub orelse t.loc.start, .keyword = t.loc.start, .open = open, .end = end });
                    z.index = end;
                    at_stmt = true;
                    continue;
                }
            },
            else => {},
        }
        if (depth == 0) at_stmt = false;
    }
    return .{ .decls = decls.items, .err = err };
}

/// `i` is `//` comment, `\\` multi-line string line, "string" or 'char': return position of its
/// last byte; else null.
/// Parameter list and `{zig}` scanners share one skip rule set (consistent with matchBraceIn),
/// doesn't skip one side and mean another.
fn skipZigLiteral(src: []const u8, from: usize) ?usize {
    var i = from;
    switch (src[i]) {
        '/', '\\' => {
            if (i + 1 >= src.len or src[i + 1] != src[i]) return null;
            while (i + 1 < src.len and src[i + 1] != '\n') i += 1;
            return i;
        },
        '"', '\'' => {
            const q = src[i];
            i += 1;
            while (i < src.len and src[i] != q and src[i] != '\n') : (i += 1) {
                if (src[i] == '\\') i += 1;
            }
            return @min(i, src.len - 1);
        },
        else => return null,
    }
}

/// Position after parameter list in declaration header: after name, if followed by `(` jump past
/// matching `)` (if unclosed, return `after_kw` unchanged)
fn headerEnd(src: []const u8, after_kw: usize) usize {
    var r = lex(src, after_kw);
    if (r.tok.tag != .ident) return after_kw;
    r = lex(src, r.next);
    if (r.tok.tag != .lparen) return after_kw;
    var depth: usize = 0;
    var i = r.tok.start;
    while (i < src.len) : (i += 1) {
        if (skipZigLiteral(src, i)) |end| {
            i = end;
            continue;
        }
        switch (src[i]) {
            '(', '[', '{' => depth += 1,
            ')', ']', '}' => {
                if (depth == 0) return after_kw;
                depth -= 1;
                if (depth == 0) return if (src[i] == ')') i + 1 else after_kw;
            },
            else => {},
        }
    }
    return after_kw;
}

/// From `from` find matching `}` (`depth0` is open depth), return its position.
/// Skip comments, "strings", 'chars', `\\` multi-line string lines: declaration boundary and `{zig
/// expression}` boundary use same rules, one doesn't win and another lose.
fn matchBraceIn(src: []const u8, from: usize, depth0: usize) ?usize {
    var depth = depth0;
    var i = from;
    while (i < src.len) : (i += 1) {
        switch (src[i]) {
            '/' => if (i + 1 < src.len and src[i + 1] == '/') {
                while (i < src.len and src[i] != '\n') i += 1;
            },
            '\\' => if (i + 1 < src.len and src[i + 1] == '\\') {
                while (i < src.len and src[i] != '\n') i += 1;
            },
            '"', '\'' => {
                const q = src[i];
                i += 1;
                while (i < src.len and src[i] != q and src[i] != '\n') : (i += 1) {
                    if (src[i] == '\\') i += 1;
                }
            },
            '{' => depth += 1,
            '}' => {
                if (depth == 0) return null;
                depth -= 1;
                if (depth == 0) return i;
            },
            else => {},
        }
    }
    return null;
}

/// Start of `///` doc comment lines immediately before `at` (return `at` if none)
fn docCommentStart(src: []const u8, at: usize) usize {
    var start = at;
    var line_start = at;
    while (line_start > 0) {
        // Previous line
        var prev_end = line_start;
        if (prev_end > 0 and src[prev_end - 1] == '\n') prev_end -= 1;
        var prev_start = prev_end;
        while (prev_start > 0 and src[prev_start - 1] != '\n') prev_start -= 1;
        const line = std.mem.trim(u8, src[prev_start..prev_end], " \t\r");
        if (!std.mem.startsWith(u8, line, "///") or std.mem.startsWith(u8, line, "////")) break;
        start = prev_start;
        if (prev_start == line_start) break;
        line_start = prev_start;
    }
    return start;
}

/// Option name as field name/enum value: write as `@"error"` if same as Zig keyword
fn optionIdent(name: []const u8) []const u8 {
    return if (std.zig.Token.getKeyword(name) != null) keywordIdents.get(name) orelse name else name;
}

/// Escaped keyword option name `@"..."` form (compile-time table, avoid runtime allocation)
const keywordIdents = blk: {
    const kws = std.zig.Token.keywords.keys();
    var pairs: [kws.len]struct { []const u8, []const u8 } = undefined;
    for (kws, 0..) |k, i| pairs[i] = .{ k, "@\"" ++ k ++ "\"" };
    break :blk std.StaticStringMap([]const u8).initComptime(pairs);
};

/// Write name as enum literal: plain identifiers as `.name`, with `-`/numeric start/keyword-same as
/// `.@"name"`
fn enumLiteral(a: Allocator, name: []const u8) ![]const u8 {
    const plain = (std.ascii.isAlphabetic(name[0]) or name[0] == '_') and std.zig.Token.getKeyword(name) == null and
        for (name) |ch| {
            if (!std.ascii.isAlphanumeric(ch) and ch != '_') break false;
        } else true;
    return if (plain) std.fmt.allocPrint(a, ".{s}", .{name}) else std.fmt.allocPrint(a, ".@\"{s}\"", .{name});
}

/// Whether this field's name value is token (per design system) or framework enum value
fn isTokenField(field: []const u8) bool {
    const p = schema.prop(field) orelse return false;
    return p.category.len != 0;
}

fn isSizing(field: []const u8) bool {
    for ([_][]const u8{ "width", "height", "min_width", "max_width", "min_height", "max_height" }) |f| if (eq(f, field)) return true;
    return false;
}

fn eq(a: []const u8, b: []const u8) bool {
    return std.mem.eql(u8, a, b);
}

// Editor analysis (yix-lsp) for outline and cursor context. Tolerates incomplete source, no error.

pub const Named = struct { name: []const u8, at: usize };
pub const DimInfo = struct { name: []const u8, at: usize, flag: bool, options: []const Named };

/// One top-level DSL declaration. body: after declaration body `{`; end: matching `}` (unclosed:
/// file end).
pub const Symbol = struct {
    kind: Kind,
    name: []const u8,
    name_at: usize,
    start: usize,
    body: usize,
    end: usize,
    slots: []const Named = &.{},
    params: []const Named = &.{},
    dims: []const DimInfo = &.{},
    /// Declaration's preceding `///` comment (stripped `///`)
    doc: []const u8 = "",

    pub const Kind = enum { recipe, style, mixin };

    pub fn dim(s: *const Symbol, name: []const u8) ?*const DimInfo {
        for (s.dims) |*d| if (eq(d.name, name)) return d;
        return null;
    }
};

/// Outline: all allocated by `a` (caller provides arena)
pub fn outline(a: Allocator, src: []const u8) ![]Symbol {
    const found = findDecls(a, src) catch return error.OutOfMemory;
    var out: std.ArrayList(Symbol) = .empty;
    for (found.decls) |d| {
        var sym: Symbol = .{ .kind = d.kind, .name = "", .name_at = d.keyword, .start = d.start, .body = src.len, .end = if (d.open != null and d.end <= src.len and d.end > 0 and src[d.end - 1] == '}') d.end - 1 else src.len };
        var r = lex(src, d.keyword + @tagName(d.kind).len);
        if (r.tok.tag == .ident) {
            sym.name = src[r.tok.start..r.tok.end];
            sym.name_at = r.tok.start;
            r = lex(src, r.next);
        }
        const header_end = d.open orelse src.len;
        if (d.kind == .recipe and r.tok.tag == .ident and eq(src[r.tok.start..r.tok.end], "slots")) {
            sym.slots = try namesInParens(a, src, r.next, header_end);
        } else if (d.kind == .mixin and r.tok.tag == .lparen) {
            sym.params = try namesInParens(a, src, r.tok.start, header_end);
        } else if (d.kind == .style and r.tok.tag == .lparen) {
            // Parameterized style: `$name` in parameter list (name excludes `$`)
            var params: std.ArrayList(Named) = .empty;
            var q = lex(src, r.next);
            while (q.tok.tag != .eof and q.tok.start < header_end) : (q = lex(src, q.next)) {
                if (q.tok.tag == .param) try params.append(a, .{ .name = src[q.tok.start + 1 .. q.tok.end], .at = q.tok.start + 1 });
            }
            sym.params = params.items;
        }
        if (d.open) |o| sym.body = o + 1;
        if (d.kind == .recipe and d.open != null) sym.dims = try dimsOf(a, src, sym.body, sym.end);
        const doc_start = docCommentStart(src, d.start);
        if (doc_start < d.start) {
            var doc: std.ArrayList(u8) = .empty;
            var lines = std.mem.splitScalar(u8, src[doc_start..d.start], '\n');
            while (lines.next()) |line| {
                const t = std.mem.trim(u8, line, " \t\r");
                if (!std.mem.startsWith(u8, t, "///")) continue;
                if (doc.items.len != 0) try doc.append(a, '\n');
                try doc.appendSlice(a, std.mem.trim(u8, t[3..], " "));
            }
            sym.doc = doc.items;
        }
        try out.append(a, sym);
    }
    return out.items;
}

/// Names inside `( a, b )` (from `from` or first `(` after, to `)` or `limit`)
fn namesInParens(a: Allocator, src: []const u8, from: usize, limit: usize) ![]const Named {
    var names: std.ArrayList(Named) = .empty;
    var r = lex(src, from);
    if (r.tok.tag != .lparen) return names.items;
    r = lex(src, r.next);
    while (r.tok.tag != .eof and r.tok.tag != .rparen and r.tok.start < limit) : (r = lex(src, r.next)) {
        if (r.tok.tag == .ident) try names.append(a, .{ .name = src[r.tok.start..r.tok.end], .at = r.tok.start });
    }
    return names.items;
}

/// `variant NAME [= x] { opt { ... } ... }` and `flag NAME ...` at first level of recipe body
fn dimsOf(a: Allocator, src: []const u8, body: usize, end: usize) ![]const DimInfo {
    var dims: std.ArrayList(DimInfo) = .empty;
    var depth: usize = 0;
    var r = lex(src, body);
    while (r.tok.tag != .eof and r.tok.start < end) : (r = lex(src, r.next)) {
        switch (r.tok.tag) {
            .lbrace => depth += 1,
            .rbrace => depth -|= 1,
            .ident => if (depth == 0) {
                const word = src[r.tok.start..r.tok.end];
                const is_flag = eq(word, "flag");
                if (!is_flag and !eq(word, "variant")) continue;
                const n = lex(src, r.next);
                if (n.tok.tag != .ident) continue;
                var d: DimInfo = .{ .name = src[n.tok.start..n.tok.end], .at = n.tok.start, .flag = is_flag, .options = &.{} };
                r = n;
                if (!is_flag) {
                    // Option: `name {` at first level of variant block
                    while (r.tok.tag != .eof and r.tok.tag != .lbrace and r.tok.start < end) r = lex(src, r.next);
                    if (r.tok.tag != .lbrace) {
                        try dims.append(a, d);
                        break;
                    }
                    var options: std.ArrayList(Named) = .empty;
                    var inner: usize = 0;
                    var prev: ?Tok = null;
                    r = lex(src, r.next);
                    while (r.tok.tag != .eof and r.tok.start < end) : (r = lex(src, r.next)) {
                        if (r.tok.tag == .lbrace) {
                            if (inner == 0) if (prev) |p| if (p.tag == .ident) try options.append(a, .{ .name = src[p.start..p.end], .at = p.start });
                            inner += 1;
                        } else if (r.tok.tag == .rbrace) {
                            if (inner == 0) break;
                            inner -= 1;
                        }
                        prev = r.tok;
                    }
                    d.options = options.items;
                }
                try dims.append(a, d);
            },
            else => {},
        }
    }
    return dims.items;
}

/// Semantic position at cursor
pub const Context = struct {
    kind: Kind,
    /// Index into outline (top-level declaration at cursor)
    symbol: ?usize = null,
    /// Word at (or adjacent to) cursor: [word_at, word_end)
    word_at: usize = 0,
    word_end: usize = 0,
    /// value: property name (as in source); empty string if mixin argument
    prop: []const u8 = "",
    /// when_option: dimension name
    dim: []const u8 = "",
    /// property: what can be written this level (flat = properties and conditions; slots = slot
    /// blocks; any = mixin body, all allowed)
    level: Level = .flat,

    pub const Kind = enum {
        /// Copied Zig or `{zig}` value: hand to ZLS
        zig,
        /// Comment, name being typed, etc.: no smarts
        none,
        /// First level of recipe body: base / variant / flag / when
        section,
        /// Condition name after `:`
        condition,
        /// Property name (or slot name, mixin name, depending on level) inside block
        property,
        /// Mixin call `name(`
        mixin_name,
        /// Slot block `name {`
        slot_name,
        /// Value in `property: ...` or argument of mixin call
        value,
        /// Dimension name in `when` condition
        when_dim,
        /// Option name after `= ` or `in (` in `when` condition; default value in `variant x = `
        when_option,
        /// Declaration name
        decl_name,
    };
    pub const Level = enum { flat, slots, any };

    pub fn word(c: Context, src: []const u8) []const u8 {
        return src[c.word_at..c.word_end];
    }
};

pub fn contextAt(src: []const u8, symbols: []const Symbol, offset: usize) Context {
    var wa = @min(offset, src.len);
    while (wa > 0 and isWordChar(src[wa - 1])) wa -= 1;
    var we = @min(offset, src.len);
    while (we < src.len and isWordChar(src[we])) we += 1;
    var ctx: Context = .{ .kind = .zig, .word_at = wa, .word_end = we };
    const idx = for (symbols, 0..) |s, i| {
        if (offset >= s.start and offset <= s.end) break i;
    } else return ctx;
    const sym = symbols[idx];
    ctx.symbol = idx;
    ctx.kind = .none;
    if (inComment(src, offset)) return ctx;
    if (offset < sym.body) {
        if (wa == sym.name_at and we > wa) ctx.kind = .decl_name;
        return ctx;
    }

    const FrameKind = enum { recipe, options, block };
    const Frame = struct { kind: FrameKind, level: Context.Level };
    var frames: [32]Frame = undefined;
    var depth: usize = 1;
    const block_level: Context.Level = if (sym.slots.len != 0) .slots else .flat;
    frames[0] = switch (sym.kind) {
        .recipe => .{ .kind = .recipe, .level = block_level },
        .style => .{ .kind = .block, .level = .flat },
        .mixin => .{ .kind = .block, .level = .any },
    };
    // Word before cursor in current statement (to previous `;` `{` `}`)
    var stmt: [16]Tok = undefined;
    var n: usize = 0;
    var pos = sym.body;
    while (true) {
        const r = lex(src, pos);
        const t = r.tok;
        // Cursor on this word (or at its end): it's word, doesn't count toward statement
        if (t.tag == .eof or t.start >= offset or (t.tag == .ident and t.start < offset and offset <= t.end)) break;
        pos = r.next;
        const top = frames[depth - 1];
        switch (t.tag) {
            .lbrace => {
                // `{zig}` in value: property value or mixin argument
                const in_value = top.kind == .block and n >= 2 and stmt[0].tag == .ident and (stmt[1].tag == .colon or stmt[1].tag == .lparen);
                if (in_value) {
                    const close = matchBraceIn(src, t.start, 0) orelse src.len;
                    if (offset <= close) {
                        ctx.kind = .zig;
                        return ctx;
                    }
                    pos = close + 1;
                    continue;
                }
                const lead: []const u8 = if (n != 0 and stmt[0].tag == .ident) src[stmt[0].start..stmt[0].end] else "";
                const next_frame: Frame = switch (top.kind) {
                    .recipe => if (eq(lead, "variant")) .{ .kind = .options, .level = block_level } else .{ .kind = .block, .level = block_level },
                    .options => .{ .kind = .block, .level = block_level },
                    .block => .{ .kind = .block, .level = .flat },
                };
                if (depth == frames.len) return ctx;
                frames[depth] = next_frame;
                depth += 1;
                n = 0;
            },
            .rbrace => {
                if (depth == 1) return ctx;
                depth -= 1;
                n = 0;
            },
            .semi => n = 0,
            else => if (n < stmt.len) {
                stmt[n] = t;
                n += 1;
            },
        }
    }
    const top = frames[depth - 1];
    const s = stmt[0..n];
    const lead: []const u8 = if (n != 0 and s[0].tag == .ident) src[s[0].start..s[0].end] else "";
    switch (top.kind) {
        .recipe => {
            if (n == 0) {
                ctx.kind = .section;
            } else if (eq(lead, "when")) {
                const last = s[n - 1];
                // `dim = |`, `dim in (|`, `dim in (a, |`
                var k = n;
                var dim: ?[]const u8 = null;
                while (k > 1) {
                    k -= 1;
                    if (s[k].tag == .amp) break;
                    if (s[k].tag == .eq or (s[k].tag == .ident and eq(src[s[k].start..s[k].end], "in"))) {
                        if (k >= 1 and s[k - 1].tag == .ident) dim = src[s[k - 1].start..s[k - 1].end];
                        break;
                    }
                }
                if (dim != null and (last.tag == .eq or last.tag == .lparen or last.tag == .comma)) {
                    ctx.kind = .when_option;
                    ctx.dim = dim.?;
                } else if (last.tag == .amp or last.tag == .bang or n == 1) {
                    ctx.kind = .when_dim;
                }
            } else if (eq(lead, "variant") and n == 3 and s[2].tag == .eq) {
                ctx.kind = .when_option;
                ctx.dim = src[s[1].start..s[1].end];
            }
        },
        .options => {},
        .block => {
            ctx.level = top.level;
            if (n == 0) {
                const after = lex(src, we).tok.tag;
                ctx.kind = switch (after) {
                    .lparen => .mixin_name,
                    .colon => .property,
                    .lbrace => if (top.level == .flat) .property else .slot_name,
                    else => .property,
                };
            } else if (n == 1 and s[0].tag == .colon) {
                ctx.kind = .condition;
            } else if (n >= 2 and s[0].tag == .ident and s[1].tag == .colon) {
                if (!eq(lead, "transition")) {
                    ctx.kind = .value;
                    ctx.prop = lead;
                }
            } else if (n >= 2 and s[0].tag == .ident and s[1].tag == .lparen) {
                ctx.kind = .value;
            }
        },
    }
    return ctx;
}

/// Cursor in line's `//` comment (DSL has no strings; `//` onward is comment)
fn inComment(src: []const u8, offset: usize) bool {
    var ls = @min(offset, src.len);
    while (ls > 0 and src[ls - 1] != '\n') ls -= 1;
    return std.mem.indexOf(u8, src[ls..@min(offset, src.len)], "//") != null;
}
