/// Runtime lowering uses the same parser and shorthand validation as Zig generation.
/// The caller owns an arena; returned slices borrow it and `source`.
pub fn compileIR(allocator: Allocator, source: []const u8) !IRResult {
    if (std.mem.indexOfAny(u8, source, &.{ compiler.mark_open, compiler.mark_text, compiler.mark_close, compiler.mark_point, compiler.mark_component })) |at|
        return .{ .diagnostic = .{ .offset = at, .message = "control characters U+0001..U+0005 are not allowed in .yss files" } };
    var c: Compiler = .{ .a = allocator, .src = source, .capture_ir = true };
    _ = c.run() catch |err| switch (err) {
        error.Yss => return .{ .diagnostic = c.diag.? },
        else => return err,
    };
    for (c.ir_declarations.items, 0..) |declaration_, i| {
        for (c.ir_declarations.items[0..i]) |previous| if (eq(previous.name, declaration_.name))
            return .{ .diagnostic = .{ .offset = declaration_.offset, .message = try std.fmt.allocPrint(allocator, "style name `{s}` is declared twice", .{declaration_.name}) } };
    }
    return .{ .ir = .{ .declarations = c.ir_declarations.items, .dependency_fingerprint = c.dependency_hash } };
}

/// Diagnostics owned by caller allocator.
pub fn compile(allocator: Allocator, source: []const u8) !Result {
    return switch (try compileMapped(allocator, source)) {
        .diagnostic => |d| .{ .diagnostic = d },
        .mapped => |m| blk: {
            allocator.free(m.segments);
            break :blk .{ .output = m.output };
        },
    };
}

/// For editor (LSP): output with position mapping. Copied Zig and `{zig}` values are byte-for-byte
/// segments; each DSL declaration maps to its source start position as a whole.
pub fn compileMapped(allocator: Allocator, source: []const u8) !MappedResult {
    return compileMappedImpl(allocator, source, null);
}

/// Generate a stable dev-preview facade while retaining the public compile API's legacy output.
/// `path` is checkout-relative; the generated twin must be beside its YSS source.
pub fn compileMappedWithPath(allocator: Allocator, source: []const u8, path: []const u8) !MappedResult {
    return compileMappedImpl(allocator, source, path);
}

pub fn compileWithPath(allocator: Allocator, source: []const u8, path: []const u8) !Result {
    return switch (try compileMappedWithPath(allocator, source, path)) {
        .diagnostic => |d| .{ .diagnostic = d },
        .mapped => |m| blk: {
            allocator.free(m.segments);
            break :blk .{ .output = m.output };
        },
    };
}

fn compileMappedImpl(allocator: Allocator, source: []const u8, path: ?[]const u8) !MappedResult {
    if (std.mem.indexOfAny(u8, source, &.{ compiler.mark_open, compiler.mark_text, compiler.mark_close, compiler.mark_point, compiler.mark_component })) |at|
        return .{ .diagnostic = .{ .offset = at, .message = try allocator.dupe(u8, "control characters U+0001..U+0005 are not allowed in .yss files") } };
    var arena = std.heap.ArenaAllocator.init(allocator);
    defer arena.deinit();
    var c: Compiler = .{ .a = arena.allocator(), .src = source, .preview_path = path };
    const marked = c.run() catch |err| switch (err) {
        error.Yss => {
            const d = c.diag.?;
            return .{ .diagnostic = .{ .offset = d.offset, .message = try allocator.dupe(u8, d.message) } };
        },
        else => return err,
    };
    var segments: std.ArrayList(Segment) = .empty;
    const out = compiler.stripMarks(c.a, marked, &segments) catch return error.OutOfMemory;
    const owned = try allocator.dupe(u8, out);
    errdefer allocator.free(owned);
    return .{ .mapped = .{ .output = owned, .segments = try allocator.dupe(Segment, segments.items) } };
}

