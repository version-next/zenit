// Lexical

/// `param`: parameterized style parameter reference `$name` (token includes `$`); `qq`: `??`
/// (fallback when parameter is null)
const Tag = enum { ident, number, hash, lbrace, rbrace, lparen, rparen, colon, semi, comma, amp, bang, eq, param, qq, other, eof };
const Tok = struct { tag: Tag, start: usize, end: usize };

/// Read one token from `pos` (skip whitespace and `//` comments first); `next` is position after
/// reading (unit `px` after number not part of token, but skipped).
/// Unknown characters are `.other`: compiler reports error, editor analysis skips.
fn lex(src: []const u8, pos0: usize) struct { tok: Tok, next: usize } {
    var pos = pos0;
    while (pos < src.len) {
        const ch = src[pos];
        if (ch == ' ' or ch == '\t' or ch == '\r' or ch == '\n') {
            pos += 1;
        } else if (ch == '/' and pos + 1 < src.len and src[pos + 1] == '/') {
            while (pos < src.len and src[pos] != '\n') pos += 1;
        } else break;
    }
    const s = pos;
    if (s >= src.len) return .{ .tok = .{ .tag = .eof, .start = s, .end = s }, .next = s };
    const ch = src[s];
    const single: ?Tag = switch (ch) {
        '{' => .lbrace,
        '}' => .rbrace,
        '(' => .lparen,
        ')' => .rparen,
        ':' => .colon,
        ';' => .semi,
        ',' => .comma,
        '&' => .amp,
        '!' => .bang,
        '=' => .eq,
        else => null,
    };
    if (single) |tag| return .{ .tok = .{ .tag = tag, .start = s, .end = s + 1 }, .next = s + 1 };
    if (ch == '?' and s + 1 < src.len and src[s + 1] == '?') return .{ .tok = .{ .tag = .qq, .start = s, .end = s + 2 }, .next = s + 2 };
    if (ch == '$' and s + 1 < src.len and (std.ascii.isAlphabetic(src[s + 1]) or src[s + 1] == '_')) {
        pos = s + 2;
        while (pos < src.len and (std.ascii.isAlphanumeric(src[pos]) or src[pos] == '_')) pos += 1;
        return .{ .tok = .{ .tag = .param, .start = s, .end = pos }, .next = pos };
    }
    if (std.ascii.isAlphabetic(ch) or ch == '_') {
        pos = s + 1;
        while (pos < src.len and isWordChar(src[pos])) pos += 1;
        return .{ .tok = .{ .tag = .ident, .start = s, .end = pos }, .next = pos };
    }
    if (std.ascii.isDigit(ch) or ((ch == '-' or ch == '.') and s + 1 < src.len and (std.ascii.isDigit(src[s + 1]) or src[s + 1] == '.'))) {
        pos = s + 1;
        while (pos < src.len and (std.ascii.isDigit(src[pos]) or src[pos] == '.')) pos += 1;
        const num_end = pos;
        // Number-starting immediately followed by letters is a name (design system allows token
        // names like `2xl`); `12px` is number plus unit
        if (std.ascii.isDigit(ch) and pos < src.len and (std.ascii.isAlphabetic(src[pos]) or src[pos] == '_')) {
            const is_px = pos + 1 < src.len and src[pos] == 'p' and src[pos + 1] == 'x' and (pos + 2 >= src.len or !isWordChar(src[pos + 2]));
            if (!is_px and std.mem.indexOfScalar(u8, src[s..pos], '.') == null) {
                while (pos < src.len and isWordChar(src[pos])) pos += 1;
                return .{ .tok = .{ .tag = .ident, .start = s, .end = pos }, .next = pos };
            }
        }
        // Units: px equivalent to raw; other units meaningful only in transition (take original)
        if (pos + 1 < src.len and src[pos] == 'p' and src[pos + 1] == 'x') pos += 2;
        return .{ .tok = .{ .tag = .number, .start = s, .end = num_end }, .next = pos };
    }
    if (ch == '#') {
        pos = s + 1;
        while (pos < src.len and std.ascii.isHex(src[pos])) pos += 1;
        return .{ .tok = .{ .tag = .hash, .start = s, .end = pos }, .next = pos };
    }
    return .{ .tok = .{ .tag = .other, .start = s, .end = s + 1 }, .next = s + 1 };
}

fn isWordChar(ch: u8) bool {
    return std.ascii.isAlphanumeric(ch) or ch == '_' or ch == '-';
}

// -- Syntax tree --

/// Value: number / name / #color / {zig} / call (mix)
const Val = union(enum) {
    num: []const u8,
    ident: struct { name: []const u8, at: usize },
    hex: []const u8,
    /// `{zig}`: source text and its position in source (byte-by-byte mapped back in generated code)
    raw: struct { text: []const u8, at: usize },
    call: struct { name: []const u8, args: []Val, at: usize },
    /// Parameterized style parameter `$name` (name excludes `$`)
    param: struct { name: []const u8, at: usize },
    /// `$name ?? fallback`: use fallback when parameter is null
    or_else: struct { name: []const u8, fallback: *const Val, at: usize },
};

/// One parameter of parameterized style: `$name: type [= default]` (type and default are raw Zig)
const Param = struct {
    name: []const u8,
    at: usize,
    ty: []const u8,
    ty_at: usize,
    default: ?[]const u8,
    default_at: usize,
    used: bool = false,

    fn optional(p: *const Param) bool {
        return p.ty.len != 0 and p.ty[0] == '?';
    }

    /// Only reject a type here when its spelling proves the mismatch. Named types and
    /// arbitrary Zig expressions may resolve to aliases; generated Zig checks those.
    fn knownNonOptional(p: *const Param) bool {
        return std.zig.isPrimitive(p.ty) or std.mem.startsWith(u8, p.ty, "*") or std.mem.startsWith(u8, p.ty, "[");
    }
};

/// Parameterized style `when condition { ... }`: condition compiled to Zig bool expression
const ParamWhen = struct { cond: []const u8, body: *Body };

/// Fields in a block: in order of appearance, later writes override earlier; sub-blocks
/// (conditions/slots) merge recursively
const Body = struct {
    keys: std.ArrayList([]const u8) = .empty,
    vals: std.ArrayList(Item) = .empty,
    ir_properties: std.ArrayList(ir.Property) = .empty,

    fn lower(b: *const Body, a: Allocator) Allocator.Error!ir.Layer {
        var conds: std.ArrayList(ir.Condition) = .empty;
        for (b.keys.items, b.vals.items) |key, val| switch (val) {
            .block => |child_body| {
                const layer = try a.create(ir.Layer);
                layer.* = try child_body.lower(a);
                try conds.append(a, .{ .name = key, .layer = layer });
            },
            .expr => {},
        };
        return .{ .properties = b.ir_properties.items, .conditions = conds.items };
    }

    fn record(b: *Body, a: Allocator, p: ir.Property) !void {
        // Preserve last-write order even when shorthand declarations overlap longhands.
        for (b.ir_properties.items, 0..) |old, i| if (eq(old.name, p.name)) {
            _ = b.ir_properties.orderedRemove(i);
            break;
        };
        try b.ir_properties.append(a, p);
    }

    const Item = union(enum) { expr: []const u8, block: *Body };

    fn find(b: *Body, key: []const u8) ?usize {
        for (b.keys.items, 0..) |k, i| if (std.mem.eql(u8, k, key)) return i;
        return null;
    }

    fn setExpr(b: *Body, a: Allocator, key: []const u8, expr: []const u8) !void {
        if (b.find(key)) |i| {
            b.vals.items[i] = .{ .expr = expr };
            return;
        }
        try b.keys.append(a, key);
        try b.vals.append(a, .{ .expr = expr });
    }

    fn child(b: *Body, a: Allocator, key: []const u8) !*Body {
        if (b.find(key)) |i| switch (b.vals.items[i]) {
            .block => |blk| return blk,
            .expr => {},
        };
        const blk = try a.create(Body);
        blk.* = .{};
        if (b.find(key)) |i| {
            b.vals.items[i] = .{ .block = blk };
        } else {
            try b.keys.append(a, key);
            try b.vals.append(a, .{ .block = blk });
        }
        return blk;
    }

    fn emit(b: *const Body, a: Allocator, out: *std.ArrayList(u8)) !void {
        try out.appendSlice(a, ".{");
        for (b.keys.items, b.vals.items) |k, v| {
            try out.appendSlice(a, " .");
            try out.appendSlice(a, k);
            try out.appendSlice(a, " = ");
            switch (v) {
                .expr => |e| try out.appendSlice(a, e),
                .block => |blk| try blk.emit(a, out),
            }
            try out.append(a, ',');
        }
        try out.appendSlice(a, " }");
    }
};

const Mixin = struct { params: [][]const u8, body_start: usize, at: usize };

const Dim = struct {
