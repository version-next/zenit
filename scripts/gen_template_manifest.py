#!/usr/bin/env python3
"""Discover all checked-in Yix acceptance inputs, fail closed on manifest drift."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
BASES = ('tests/yix', 'src/ui/components', 'examples/storybook')
HOST_MANIFEST = ROOT / 'tests/yix/component_root_hosts.json'
MANIFEST = ROOT / 'tests/yix/template_equivalence_manifest.json'
ZIG = ROOT / 'src/ui/template_equivalence_manifest.zig'

def discover(root=ROOT):
    rows = []
    for path in sorted(p for base in BASES for p in (root / base).rglob('*.yix')):
        twin = path.with_name('_' + path.name + '.zig')
        if not twin.is_file():
            raise ValueError(f'missing generated twin: {path.relative_to(root)}')
        names = re.findall(r'pub fn (\w+)\(args: anytype\) ui\.view\.(?:ComponentOf|SlottedOf)\(', twin.read_text())
        if not names:
            raise ValueError(f'no component in {path.relative_to(root)}')
        rows.append({'source': path.relative_to(root).as_posix(), 'components': names})
    if not rows:
        raise ValueError('empty discovery')
    return rows

def generated(rows, external):
    code = ['// GENERATED by scripts/gen_template_manifest.py; do not edit.']
    if not external:
        code += ['const gate = @import("template_equivalence_tests.zig");']
    selected = [row for row in rows if (not row['source'].startswith('src/ui/')) == external]
    for i, row in enumerate(selected):
        source = row['source']
        twin = str(Path(source).with_name('_' + Path(source).name + '.zig'))
        imp = f'lp3_fixture_{i}' if external else twin[len('src/ui/'):]
        code.append(f'const fixture{i} = @import({json.dumps(imp)});')
    code += ['pub fn run(comptime gate: type) !void {' if external else 'pub fn run() !void {']
    for i, row in enumerate(selected):
        for name in row['components']:
            code.append(f'    try gate.check(fixture{i}, {json.dumps(name)}, {json.dumps(row["source"] + ":" + name)});')
    if not external:
        code.append('    try @import("zenit_environment").preview.fixtures.run(gate);')
    code += ['}', '']
    return '\n'.join(code)

TOKEN = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|[A-Za-z_]\w*|\S')
HOSTS = {
    'date_picker/mod.zig': 'DatePicker captures ControlShell trigger parts and Input time-editor results; capture pins their component roots.',
    'date_range_picker/mod.zig': 'DateRangePicker captures ControlShell trigger slots before retaining start/end/chevron aliases; capture pins the shell root.',
    'select/mod.zig': 'Select stores ControlShell parts; capture pins the complete parts.',
    'tags_input/mod.zig': 'TagsInput captures Input results and the Add Button; Input pins its inner shell and Button capture pins its component root.',
    'input/mod.zig': 'Input stores ControlShell parts; capture pins the complete parts.',
    'input/textarea.zig': 'Textarea, including embedded, captures ControlShell parts before retaining surface/selection aliases.',
    'file_upload/mod.zig': 'FileUploadResult browse_button explicitly pins the retained Button root.',
    'window_chrome/caption.zig': 'WindowControls explicitly pins retained caption Button roots.',
    'group/mod.zig': 'Group pins each imperative retained child.',
    'grid/mod.zig': 'Grid delegates pooled cell scope ownership to view.renderInto.',
    'table/mod.zig': 'Table delegates cell, virtual row and separator scope ownership to view.renderInto.',
    'virtual_list/mod.zig': 'VirtualList delegates pooled row scope ownership to view.renderInto.',
}

def calls(source):
    tokens = [m[0] for m in TOKEN.finditer(source) if not m[0].startswith(('//', '/*'))]
    result = []
    for i, token in enumerate(tokens):
        if token not in ('pinComponentRoot', 'renderInto') or i + 1 == len(tokens) or tokens[i + 1] != '(':
            continue
        if i and tokens[i - 1] == 'fn':
            continue
        depth = 0
        for end in range(i + 1, len(tokens)):
            if tokens[end] == '(':
                depth += 1
            elif tokens[end] == ')':
                depth -= 1
                if depth == 0:
                    result.append(' '.join(tokens[i:end + 1]))
                    break
        else:
            raise ValueError('unterminated host call')
    return sorted(result)

# check_orphan_tests.sh temporarily plants this exact line in the first test of
# each file; it is not a host change, so it must not count as audit drift.
ORPHAN_PROBE_LINE = re.compile(rb'\n    @import\("std"\)\.debug\.print\("ORPHAN-PROBE-HIT [^"\n]*\\n", \.\{\}\);')


def host_digest(path):
    return hashlib.sha256(ORPHAN_PROBE_LINE.sub(b'', path.read_bytes())).hexdigest()


def inventory(root=ROOT):
    sites = {}
    for path in sorted((root / 'src/ui').rglob('*.zig')):
        found = calls(path.read_text())
        if found:
            sites[path.relative_to(root).as_posix()] = found
    hosts = {}
    for name, contract in HOSTS.items():
        path = root / 'src/ui/components' / name
        hosts[name] = {'contract': contract, 'sha256': host_digest(path)}
    return {'calls': sites, 'reviewed_native_hosts': hosts}

def validate_hosts(expected, actual):
    if actual != expected:
        raise ValueError('root-host audit drift: review all changed calls/hosts; regenerate with --write after review')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check-hosts', action='store_true')
    parser.add_argument('--write-hosts', action='store_true')
    args = parser.parse_args()
    if args.check_hosts or args.write_hosts:
        actual = inventory()
        if args.write_hosts:
            HOST_MANIFEST.write_text(json.dumps(actual, indent=2) + '\n')
        else:
            validate_hosts(json.loads(HOST_MANIFEST.read_text()), actual)
        print(f'LP3 root-host audit: {sum(map(len, actual["calls"].values()))} calls, {len(HOSTS)} native hosts')
        return
    rows = discover()
    externals = [str(Path(row['source']).with_name('_' + Path(row['source']).name + '.zig')) for row in rows if not row['source'].startswith('src/ui/')]
    source_list = '// GENERATED by scripts/gen_template_manifest.py; do not edit.\n' + 'pub const sources = [_][]const u8{\n' + ''.join('    ' + json.dumps(p) + ',\n' for p in externals) + '};\n'
    outputs = {MANIFEST: json.dumps(rows, indent=2) + '\n', ZIG: generated(rows, False), ROOT / 'tools/template_equivalence_sources.zig': source_list + generated(rows, True)}
    if args.write:
        for path, content in outputs.items():
            path.write_text(content)
    else:
        for path, content in outputs.items():
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f'LP3 manifest drift: {path.relative_to(ROOT)}; run gen_template_manifest.py --write')
    print(f'LP3 manifest: {len(rows)} sources, {sum(len(r["components"]) for r in rows)} components')

if __name__ == '__main__':
    main()
