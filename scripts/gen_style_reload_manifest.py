#!/usr/bin/env python3
"""Fail closed on an unrepresented YSS source; generated test imports stay typed."""
import argparse
import re
import subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def render():
    paths = sorted(subprocess.check_output(['rg', '--files', '-g', '*.yss'], cwd=ROOT, text=True).splitlines())
    lines = ['// Generated by scripts/gen_style_reload_manifest.py. Do not edit.',
             'const checks = @import("style_reload_tests.zig");',
             'const fixtures = @import("zenit_environment").preview.fixtures;',
             'test "LP2 all repository YSS evaluation manifest" {',
             '    var counts: checks.Counts = .{};']
    fixtures = ['// Generated by scripts/gen_style_reload_manifest.py. Do not edit.',
                '// Repository-level imports are private to the LP2 test graph.',
                'pub const theme_source = @import("lp2_theme_source").bytes;']
    for i, path in enumerate(paths):
        twin = str(Path(path).with_name('_' + Path(path).name + '.zig'))
        if path.startswith('src/ui/'):
            ns = '@import("' + twin[len('src/ui/'):] + '")'
            embed = '@embedFile("' + path[len('src/ui/'):] + '")'
        else:
            ns = 'fixtures.fixture_' + str(i)
            fixtures.append(f'pub const fixture_{i} = @import("lp2_fixture_{i}");')
            # Each fixture wrapper exposes source bytes from its own directory.
            embed = 'fixtures.source_' + str(i)
            fixtures.append(f'pub const source_{i} = @import("lp2_source_{i}").bytes;')
        lines.append(f'    try checks.checkNamespace({ns}, {embed}, "{path}", &counts);')
    lines += [f'    try checks.finish(counts, {len(paths)});', '}','']
    return {'src/ui/style_reload_manifest.zig': '\n'.join(lines),
            'tools/style_reload_fixtures.zig': '\n'.join(fixtures) + '\n'}

def main():
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args=parser.parse_args()
    for name, text in render().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text()!=text: raise SystemExit('stale YSS evaluation manifest: ' + name + '; run scripts/gen_style_reload_manifest.py')
        else: path.write_text(text)
if __name__ == '__main__': main()
